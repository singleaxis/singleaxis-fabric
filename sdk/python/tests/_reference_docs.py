def source_variables() -> set[str]:
    """``FABRIC_*`` string literals in the Python SDK and CLI (and the TS-only ones), but
    the file forms (documented with their variable) and the Node's own variables."""
    found: set[str] = set()
    for path in (ROOT / "sdk/python/src/fabric").rglob("*.py"):
        if path.name.startswith("_") and path.name.endswith("_data.py"):
            continue  # generated catalogue texts name variables in fixes, not reads
        found |= set(re.findall(r"[\"'](FABRIC_[A-Z0-9_]+)[\"']", path.read_text("utf-8")))
    return found - NOT_VARIABLES - NODE_VARIABLES - set(FILE_FORMS)


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def _cell(text: str) -> str:
    """A table cell of prose: pipes escaped and each bare ``NAME_*`` set as code, so its
    ``*`` is not read as emphasis (markdownlint MD037)."""
    return _escape(re.sub(r"(?<![`\w])([A-Z][A-Z0-9_]*_\*)(?!`)", r"`\1`", text))


def render_cli() -> str:
    from fabric import cli  # noqa: PLC0415

    parser = cli.build_parser()
    lines = ["# CLI reference", "", HEADER, "",
             "Every `fabric` command and its options, as `fabric COMMAND --help` prints them.",
             "Options on every command: `--config PATH`, `--project NAME`, `--json`, `--quiet`,",
             "`--no-color`. Exit codes: 0 ok, 1 a check did not pass, 2 usage or configuration",
             "error, 3 a prerequisite is missing; `fabric run` exits with the agent's code.", ""]  # fmt: skip
    common = {"--config", "--project", "--json", "--quiet", "--no-color", "-h", "--help"}
    for name, sub in parser.commands.items():
        summary = cli._SUMMARIES[name]
        built = "" if name in cli.BUILT else " Not built in this release (`FC-010`)."
        lines += [f"## fabric {name}", "", f"{summary[:1].upper()}{summary[1:]}.{built}", ""]
        rows = []
        for action in sub._actions:
            options = [o for o in action.option_strings if o not in common]
            if not action.option_strings or not options:
                if not action.option_strings and action.dest not in ("help",):
                    rows.append((str(action.metavar or action.dest), action.help or ""))
                continue
            metavar = ""
            if action.nargs != 0 and not isinstance(action, argparse._StoreConstAction):
                metavar = " " + str(action.metavar or (
                    "{" + ",".join(map(str, action.choices)) + "}" if action.choices
                    else action.dest.upper()))  # fmt: skip
            rows.append((", ".join(f"{o}{metavar}" for o in options), action.help or ""))
        if rows:
            lines += ["| Option | What it does |", "|---|---|"]
            lines += [f"| `{_escape(o)}` | {_cell(str(h).replace('%%', '%'))} |" for o, h in rows]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _schema_at(schema: dict[str, Any], key: str) -> dict[str, Any]:
    node: dict[str, Any] = schema
    for part in key.split("."):
        node = (node.get("properties") or {}).get(part, {})
    return node


def _kind(node: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in node:
        return _kind(defs[node["$ref"].rsplit("/", 1)[1]], defs)
    if "enum" in node:
        return " \\| ".join(f"`{v}`" for v in node["enum"])
    if "const" in node:
        return f"`{node['const']}`"
    if "oneOf" in node:
        return " or ".join(_kind(n, defs) for n in node["oneOf"])
    kind = node.get("type")
    if kind == "array":
        return f"list of {_kind(node.get('items', {}), defs)}"
    return {"string": "text", "boolean": "`true` \\| `false`", "integer": "number",
            "object": "mapping", "null": "`null`"}.get(str(kind), str(kind or "mapping"))  # fmt: skip


def _value(value: Any) -> str:
    if value is None:
        return "none"
    return f"`{json.dumps(value) if not isinstance(value, str) else value}`"


def render_fabric_yaml() -> str:
    from fabric.cli import _config  # noqa: PLC0415

    schema = json.loads(SCHEMA.read_text("utf-8"))
    defs = schema.get("$defs") or {}
    local, production = (
        _config.defaults("local", "PROJECT"),
        _config.defaults("production", "PROJECT"),
    )
    lines = ["# fabric.yaml reference", "", HEADER, "",
             "`fabric.yaml` (schema `fabric.config/v1`) is what `fabric init` writes and every",
             "command reads; the SDK and the Node never read it (the CLI compiles it into their",
             "settings). For each setting the first source that sets it wins: a flag on the",
             "command, then an environment variable already set, then fabric.yaml, then the",
             "profile's default. Unknown keys are refused with the nearest valid key.", "",
             "| Key | Values | Default (local) | Default (production) | Variable that overrides it |",
             "|---|---|---|---|---|"]  # fmt: skip
    for setting in _config.SETTINGS:
        node = _schema_at(schema, setting.key)
        env = f"`{setting.env}`" if setting.env else ""
        lines.append(f"| `{setting.key}` | {_kind(node, defs) if node else 'mapping'} | "
                     f"{_value(local.get(setting.key))} | {_value(production.get(setting.key))} "
                     f"| {env} |")  # fmt: skip
    lines += ["", "`PROJECT` stands for the project name (the directory's name by default)."]
    return "\n".join(lines) + "\n"


def render_env_vars() -> str:
    lines = ["# Environment variables", "", HEADER, "",
             "The `FABRIC_*` variables the SDKs and the CLI read. `fabric run` sets the ones an",
             "agent needs from fabric.yaml; a variable already set in the shell wins over",
             "fabric.yaml. Keys and tokens are passed by file (`*_FILE`), never by value, on the",
             "default path. Fabric never sets or changes an `OTEL_*` variable. Python only",
             "unless marked TS or Python and TS.", ""]  # fmt: skip
    group = None
    for section, name, text in VARIABLES:
        if section != group:
            lines += ["", f"## {section}", "", "| Variable | What it does |", "|---|---|"]
            group = section
        lines.append(f"| `{name}` | {_cell(text)} |")
    lines += ["", "`FABRIC_TOKENIZATION_KEY_FILE` and `FABRIC_WIRE_SPOOL_KEY_FILE` are the file",
              "forms of their keys."]  # fmt: skip
    return "\n".join(line for line in _squeeze(lines)) + "\n"


def _squeeze(lines: Iterable[str]) -> Iterable[str]:
    previous = None
    for line in lines:
        if line == "" and previous == "":
            continue
        previous = line
        yield line


