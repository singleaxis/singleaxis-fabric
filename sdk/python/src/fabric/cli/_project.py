"""A project (spec 058 §5.1): the directory with ``fabric.yaml``, its state in ``.fabric/``
beside it, its secrets directory, and the compiled environment file (§6.5).

``.fabric/compiled.env`` is the environment ``fabric run`` gives an agent, with a file path
for every secret and never a value. It is a pure function of ``fabric.yaml`` (variables set
in the shell win later, at ``run``), carries the digest of the ``fabric.yaml`` it came
from, and is rewritten whenever that file changes."""

from __future__ import annotations

import contextlib
import hashlib
import ipaddress
import os
import secrets as _random
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import unquote, urlsplit

from . import _config, _providers, _secrets
from ._report import CliError, Finding

STATE_DIR = ".fabric"
COMPILED_ENV = "compiled.env"
DEFAULT_NODE_PORT = 4318
_DIGEST_PREFIX = "# fabric-yaml-sha256: "
_HEADER = (
    "# Generated by `fabric init` from fabric.yaml (spec 058 section 6.5). Do not edit: it is\n"
    "# rewritten when fabric.yaml changes. One KEY=value per line; the value is everything\n"
    "# after the first '='. Secrets appear as file paths, never as values.\n"
)


@dataclass(frozen=True)
class Project:
    """Everything the commands need to know about one project."""

    directory: Path
    config_path: Path
    document: dict[str, Any]
    resolved: _config.Resolved  # fabric.yaml and defaults only (what compiles)
    secrets_dir: Path

    @property
    def name(self) -> str:
        return str(self.resolved["project"])

    @property
    def state_dir(self) -> Path:
        return self.directory / STATE_DIR

    @property
    def compiled_env_path(self) -> Path:
        return self.state_dir / COMPILED_ENV

    @property
    def compose_project(self) -> str:
        """The Compose project name. Always prefixed, so it can never be the name Docker
        Compose gives the customer's own project in the same directory (I5)."""
        return f"fabric-{self.name}"[:63].rstrip("-")

    @property
    def data_dir(self) -> Path:
        destination = self.resolved["destination"] or {}
        path = Path(str(destination.get("path") or "./fabric-data")).expanduser()
        return path if path.is_absolute() else (self.directory / path)

    @property
    def id_key_file(self) -> Path | None:
        referenced = self.resolved["secrets.id_key_file"]
        if referenced:
            return _absolute(self.directory, str(referenced))
        return self.secrets_dir / _secrets.ID_KEY

    @property
    def generates_tls(self) -> bool:
        """A local Node needs the generated CA and certificate; an external Node has its own."""
        return bool(self.resolved["node.mode"] == "docker")

    @property
    def ca_file(self) -> Path | None:
        """The CA agents verify the Node with: the generated one for a local Node (its
        certificate is issued from it), a referenced one for an external Node."""
        if self.generates_tls:
            return self.secrets_dir / _secrets.CA_CERT
        referenced = self.resolved["secrets.ca_file"]
        return _absolute(self.directory, str(referenced)) if referenced else None


def _absolute(directory: Path, value: str) -> Path:
    path = Path(value).expanduser()
    return path if path.is_absolute() else (directory / path)


def load(located: _config.Located, flags: Mapping[str, Any], environ: Mapping[str, str],
         document: dict[str, Any] | None = None) -> Project:  # fmt: skip
    """The project of a located ``fabric.yaml`` (``document``: already loaded and valid)."""
    if located.path is None:
        raise CliError([Finding("FC-001")])
    document = _config.load(located) if document is None else document
    directory = located.path.resolve().parent
    resolved = _config.resolve(document, flags, {}, directory)
    secrets_dir = _secrets.secrets_dir(str(resolved["secrets.dir"]), str(resolved["project"]),
                                       directory, environ)  # fmt: skip
    return Project(directory, located.path, document, resolved, secrets_dir)


def ensure_state_dir(project: Project) -> Path:
    """``.fabric/`` beside ``fabric.yaml``, mode 0700 (§5.1). A symlink is refused: the
    project directory may be a checkout of somebody else's repository, and `down --purge`
    deletes ``.fabric/state``."""
    path = project.state_dir
    if path.is_symlink():
        raise CliError([Finding("FC-012", f"{path}: is a symlink")])
    path.mkdir(mode=0o700, exist_ok=True)
    if os.name == "posix":
        path.chmod(0o700)
    return path


def node_port(resolved: _config.Resolved) -> int:
    """The loopback port a local Node's OTLP/HTTP TLS listener is published on: 4318, or
    the port of ``node.endpoint`` (which must then be an https loopback URL)."""
    endpoint = resolved["node.endpoint"]
    if endpoint == "auto":
        return DEFAULT_NODE_PORT
    parts = urlsplit(str(endpoint))
    host = parts.hostname or ""
    if parts.scheme != "https" or not _is_loopback(host):
        raise CliError(
            [
                Finding(
                    "FC-004",
                    "node.endpoint: with node.mode: docker it must be auto or "
                    "https://localhost:PORT (the local Node listens on loopback over TLS)",
                )
            ]
        )
    return parts.port or 443


def _is_loopback(host: str) -> bool:
    if host == "localhost":
        return True
    try:
        return ipaddress.ip_address(host).is_loopback
    except ValueError:
        return False


def node_endpoint(resolved: _config.Resolved) -> str:
    """The base URL agents send records to (``FABRIC_OTLP_ENDPOINT``)."""
    if resolved["node.mode"] == "docker":
        return f"https://localhost:{node_port(resolved)}"
    endpoint = str(resolved["node.endpoint"])
    if endpoint == "auto":
        raise CliError(
            [
                Finding(
                    "FC-004",
                    f"node.endpoint: is required with node.mode: {resolved['node.mode']} "
                    "(the https URL of the existing Node)",
                )
            ]
        )
    return endpoint.rstrip("/")


def _check_compilable(project: Project) -> None:
    """Refuse what this release cannot compile, before anything is written."""
    resolved = project.resolved
    if resolved["profile"] != "local":
        raise CliError([Finding("FC-011", "profile: production")])
    if not resolved["providers.builtin"]:
        raise CliError([Finding("FC-011", "providers.builtin: false")])
    # Accepted by fabric.config/v1 and compiled by later work packages (E4; 057 WP7-9):
    # a value that would be ignored is refused, never dropped without a word.
    if resolved["node.queue_size"] != "auto":
        raise CliError([Finding("FC-011", "node.queue_size (leave it at auto)")])
    if resolved["capture.security_context"] is not None:
        raise CliError([Finding("FC-011", "capture.security_context (remove the line)")])
    if project.generates_tls and resolved["secrets.ca_file"]:
        # Agents given another CA would refuse the local Node's certificate and record
        # nothing; refuse the combination instead of compiling it.
        raise CliError(
            [
                Finding(
                    "FC-004",
                    "secrets.ca_file: is the CA of an existing Node, but node.mode: docker "
                    "starts a local Node with its own generated CA; remove secrets.ca_file, "
                    "or set node.mode: external and node.endpoint to that Node",
                )
            ]
        )


def compile_environment(project: Project) -> dict[str, str]:
    """§6.5: the ``FABRIC_*`` environment of spec 058 §5.5 step 3 that does not depend on
    one run. File paths for every secret; no ``OTEL_*`` name (I2)."""
    resolved = project.resolved
    _check_compilable(project)
    env: dict[str, str] = {
        "FABRIC_TENANT_ID": str(resolved["tenant"]),
        "FABRIC_AGENT_ID": str(resolved["agent"]),
        "FABRIC_OTLP_ENDPOINT": node_endpoint(resolved),
    }
    if project.ca_file is not None:
        env["FABRIC_OTLP_CERTIFICATE"] = str(project.ca_file)
    destination = resolved["destination"] or {}
    if resolved["capture.content"] and destination.get("preset") == "local-dir":
        env["FABRIC_WIRE_STORE"] = (project.data_dir / "store").resolve().as_uri()
    if project.id_key_file is not None:
        env["FABRIC_WIRE_ID_KEY_FILE"] = str(project.id_key_file)
    custom = _providers.custom_from_config(resolved["providers.custom"] or [])
    if custom:
        env["FABRIC_WIRE_ENDPOINTS"] = _providers.endpoints_value([d.matcher for d in custom])
    if resolved["capture.exec"]:
        env["FABRIC_WIRE_EXEC"] = "1"
    if resolved["capture.http_hosts"]:
        env["FABRIC_WIRE_HTTP_HOSTS"] = ",".join(resolved["capture.http_hosts"])
    if resolved["capture.mcp"]:
        env["FABRIC_WIRE_MCP"] = "1"
    if resolved["capture.privacy"] != "profile-default":
        env["FABRIC_CAPTURE_POLICY"] = str(_absolute(project.directory,
                                                     str(resolved["capture.privacy"])))  # fmt: skip
    for name, value in env.items():
        if "\n" in value or "\r" in value:
            raise CliError([Finding("FC-004", f"{name}: the value has a line break")])
    return env


def store_directory(uri: str) -> Path | None:
    """The directory a ``file://`` ``FABRIC_WIRE_STORE`` names, decoded as the SDK decodes
    it (``as_uri`` writes a space as ``%20``); ``None`` for any other store."""
    parts = urlsplit(uri)
    if parts.scheme != "file" or parts.netloc not in ("", "localhost"):
        return None
    return Path(unquote(parts.path))


def config_digest(config_path: Path) -> str:
    return hashlib.sha256(config_path.read_bytes()).hexdigest()


def render_compiled_env(env: Mapping[str, str], digest: str) -> str:
    lines = [f"{name}={value}" for name, value in env.items()]
    return _HEADER + _DIGEST_PREFIX + digest + "\n" + "\n".join(lines) + "\n"


def write_compiled_env(project: Project) -> tuple[Path, bool]:
    """Write ``.fabric/compiled.env`` (0600, atomic). Returns its path and whether the
    content changed."""
    text = render_compiled_env(compile_environment(project), config_digest(project.config_path))
    path = ensure_state_dir(project) / COMPILED_ENV
    with contextlib.suppress(OSError, UnicodeDecodeError):  # missing or unreadable: write it
        if path.read_text(encoding="utf-8") == text and not path.is_symlink():
            return path, False
    temporary = path.with_name(f".{COMPILED_ENV}.{_random.token_hex(6)}.tmp")
    _secrets.write_new(temporary, text.encode("utf-8"), 0o600)
    os.replace(temporary, path)
    return path, True


def read_compiled_env(path: Path) -> tuple[str | None, dict[str, str]]:
    """The digest a compiled environment file carries, and its variables."""
    digest: str | None = None
    env: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith(_DIGEST_PREFIX):
            digest = line[len(_DIGEST_PREFIX) :].strip()
        elif line and not line.startswith("#") and "=" in line:
            name, _, value = line.partition("=")
            env[name] = value
    return digest, env


def compiled_env_is_current(project: Project) -> bool:
    """Whether ``.fabric/compiled.env`` came from the current ``fabric.yaml`` (§6.5: so
    ``doctor`` can detect a stale file)."""
    try:
        digest, _ = read_compiled_env(project.compiled_env_path)
    except (OSError, UnicodeDecodeError):
        return False
    return digest == config_digest(project.config_path)


def gitignore_entries(project: Project) -> list[str]:
    """Add ``.fabric/`` (and a data directory inside the project: it holds captured
    content) to ``.gitignore`` when the project is in a git work tree (§5.1). Returns the
    lines added."""
    if _config._git_root(project.directory) is None:
        return []
    wanted = [f"/{STATE_DIR}/"]
    # A secrets directory (`secrets.dir: ./...`) or data directory inside the project: the
    # keys and the captured content must never be one `git add -A` away from a commit.
    for inside in (project.secrets_dir, project.data_dir):
        with contextlib.suppress(ValueError):  # outside the project: not ours to list
            relative = inside.resolve().relative_to(project.directory.resolve())
            entry = f"/{relative.as_posix()}/"
            if relative.parts and entry not in wanted:  # never the project directory itself
                wanted.append(entry)
    path = project.directory / ".gitignore"
    try:
        existing = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        existing = ""
    except (OSError, UnicodeDecodeError):
        return []
    present = {line.strip().strip("/") for line in existing.splitlines()}
    missing = [entry for entry in wanted if entry.strip("/") not in present]
    if not missing or path.is_symlink():
        return []
    prefix = "" if not existing or existing.endswith("\n") else "\n"
    block = prefix + "# SingleAxis Fabric local state and captured data\n" + "\n".join(missing)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(block + "\n")
    return missing
