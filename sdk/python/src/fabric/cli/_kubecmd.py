"""The ``--kubernetes`` form of ``fabric plan``, ``up``, ``down``, ``verify`` and
``doctor`` (spec 058 §5.2, §5.4, §5.6, §5.7, §10.6).

- ``plan --kubernetes`` reads the cluster (read-only) and predicts what Fabric would
  record there: which nodes can run the host sensor, which RuntimeClasses it cannot see
  into, whether a release is installed, and the next command.
- ``up --kubernetes`` runs one ``helm upgrade --install`` of the Fabric chart at this
  CLI's version with a preset; ``--render DIR`` writes the values and the Secret
  manifests instead, for a GitOps pipeline. ``down --kubernetes`` runs one
  ``helm uninstall``; ``--purge`` also deletes the Secrets Fabric generated.
- ``verify --kubernetes`` checks the release (Secrets, Node, injector and the pods it
  served, the host sensor's ``pods_scoped`` and ``pods_unscoped`` per node,
  NetworkPolicies), sends the canary through a port-forward it opens and closes (a Node
  that takes no token), and reads the last run back from ``--spans``.
- ``doctor --kubernetes`` runs the same checks and says why a pod runs uncaptured.

Boundary: these act once, on the current kube context (I5). ``up`` and ``down`` touch
only Fabric's own release and, with ``--purge``, the Secrets labelled as generated by
Fabric; no command restarts, scales, rolls out or deletes any other workload, and none
runs ``exec`` in a pod. They contact only that cluster's API server, through ``kubectl``
and ``helm``, and (``up``) the chart registry (I4)."""

