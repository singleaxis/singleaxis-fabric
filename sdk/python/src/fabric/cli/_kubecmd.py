def _helm(environ: Mapping[str, str], which: Callable[..., str | None]) -> str:
    found = which("helm", path=environ.get("PATH", os.defpath))
    if not found:
        raise CliError([Finding("FC-121")], EXIT_PREREQUISITE)
    return found


def _tail(text: str, lines: int = 3) -> str:
    kept = [line.strip() for line in (text or "").splitlines() if line.strip()]
    return " | ".join(kept[-lines:])[:900] or "no output"


def _run(runner: Callable[..., Any], argv: Sequence[str], environ: Mapping[str, str],
         timeout: float) -> Any:  # fmt: skip
    try:
        return runner(list(argv), capture_output=True, text=True, check=False,
                      timeout=timeout, stdin=subprocess.DEVNULL, env=dict(environ))  # fmt: skip
    except subprocess.TimeoutExpired:
        raise CliError(
            [Finding("FC-123", f"{Path(argv[0]).name} {argv[1]} did not finish in {timeout:g} s")],
            EXIT_FINDINGS,
        ) from None
    except OSError as exc:
        raise CliError(
            [Finding("FC-123", f"{Path(argv[0]).name}: {type(exc).__name__}")], EXIT_PREREQUISITE
        ) from None


def _tenant(options: argparse.Namespace, environ: Mapping[str, str], cwd: Path) -> str | None:
    """``--tenant``, else the tenant of the project's ``fabric.yaml`` when there is one."""
    if options.tenant:
        return str(options.tenant)
    located = _config.discover(options.config, environ, cwd)
    if located.path is None or not located.path.is_file():
        return None
    try:
        return str(_project.load(located, {}, environ).resolved["tenant"])
    except CliError:
        return None


def _values(options: argparse.Namespace, tenant: str | None,
            nodes: Sequence[str] = ()) -> dict[str, Any]:  # fmt: skip
    values: dict[str, Any] = {"preset": options.preset}
    if tenant:
        values["tenant"] = {"id": tenant}
    if options.agent_namespace:
        values["agentNamespaces"] = list(options.agent_namespace)
    if options.injector:
        values["injector"] = {"enabled": True}
    if nodes:
        values["hostSensor"] = {"nodes": list(nodes)}
    return values


def _check_up(options: argparse.Namespace) -> None:
    _kube.check_namespace(options.namespace, "release namespace")
    _kube.check_namespace(options.release, "release name")
    for name in options.agent_namespace or []:
        _kube.check_namespace(name, "agent namespace")
    for value in options.set or []:
        if not _HELM_VALUE.fullmatch(value):
            raise CliError([Finding("FC-151", f"--set takes KEY=VALUE, not {value!r}")])
    for path in options.values or []:
        if not Path(path).is_file():
            raise CliError([Finding("FC-151", f"--values {path}: no such file")])
    if options.injector and not options.agent_namespace:
        raise CliError(
            [Finding("FC-151", "--injector needs --agent-namespace NAMESPACE: the injector "
                     "serves only the namespaces the release has Secrets for")]
        )  # fmt: skip


def _chart(options: argparse.Namespace, environ: Mapping[str, str],
           findings: list[Finding]) -> tuple[str, list[str]]:  # fmt: skip
    """The chart to install and its version arguments: this release's chart, pinned to
    the CLI's own version (§11.2), unless ``--chart`` or ``FABRIC_CHART`` names another."""
    chart = options.chart or (environ.get(CHART_ENV) or "").strip() or CHART
    if not options.chart and chart != CHART:
        findings.append(Finding("FC-152", chart))
    return chart, (["--version", __version__] if chart.startswith("oci://") else [])


def helm_arguments(options: argparse.Namespace, tenant: str | None, chart: str,
                   version: Sequence[str], wait_s: float) -> list[str]:  # fmt: skip
    """``helm upgrade --install`` for the release: values as ``--set`` flags (none of them
    is a secret), the operator's own files and flags after them, so theirs win."""
    args = ["upgrade", "--install", options.release, chart, *version,
            "--namespace", options.namespace, "--create-namespace",
            "--set", f"preset={options.preset}"]  # fmt: skip
    if tenant:
        args += ["--set-string", f"tenant.id={tenant}"]
    if options.agent_namespace:
        args += ["--set", "agentNamespaces={" + ",".join(options.agent_namespace) + "}"]
    if options.injector:
        args += ["--set", "injector.enabled=true"]
    for path in options.values or []:
        args += ["--values", str(path)]
    for value in options.set or []:
        args += ["--set", value]
    return [*args, "--wait", "--timeout", f"{int(max(wait_s, 1))}s"]


def run_up(
    options: argparse.Namespace,
    environ: Mapping[str, str] | None = None,
    cwd: Path | None = None,
    *,
    runner: Callable[..., Any] = subprocess.run,
    which: Callable[..., str | None] = shutil.which,
    cluster: Cluster | None = None,
) -> tuple[Report, list[str]]:
    """``fabric up --kubernetes``: one ``helm upgrade --install`` of the Fabric release,
    or (``--render``) the values and Secret manifests for the operator's own pipeline."""
    environ = os.environ if environ is None else environ
    cwd = cwd or Path.cwd()
    _check_up(options)
    findings: list[Finding] = []
    report = Report("up", findings=findings)
    tenant = _tenant(options, environ, cwd)
    chart, version = _chart(options, environ, findings)
    wait_s = options.wait if options.wait != 60.0 else DEFAULT_HELM_WAIT_S  # noqa: PLR2004
    if options.render:
        return _render(options, environ, tenant, chart, version, wait_s, report, which, cluster)
    helm = _helm(environ, which)
    args = helm_arguments(options, tenant, chart, version, wait_s)
    result = _run(runner, [helm, *args], environ, wait_s + 60)
    if result.returncode != 0:
        raise CliError([*findings, Finding("FC-123", _tail(result.stderr))], EXIT_FINDINGS)
    findings.append(Finding("FC-124", f"release {options.release}, namespace {options.namespace}"))
    report.data = {"kubernetes": {
        "release": options.release, "namespace": options.namespace, "preset": options.preset,
        "chart": chart, "chart_version": version[1] if version else None,
        "agent_namespaces": list(options.agent_namespace or []),
        "injector": bool(options.injector), "rendered": None,
    }}  # fmt: skip
    lines = [
        f"Fabric release {options.release} in namespace {options.namespace}: preset "
        f"{options.preset}, chart {chart}" + (f" {version[1]}" if version else ""),
    ]
    lines.extend(_next_steps(options))
    return report, lines


def _next_steps(options: argparse.Namespace) -> list[str]:
    if not options.agent_namespace:
        return ["next: name your agents' namespaces: fabric up --kubernetes "
                "--agent-namespace NAMESPACE --injector"]  # fmt: skip
    first = options.agent_namespace[0]
    if not options.injector:
        return [f"next: give the agent pods of {first} their settings with "
                "`fabric run --print-env --format k8s`, or add --injector"]  # fmt: skip
    return [
        f"next: kubectl label namespace {first} fabric.singleaxis.ai/injection=enabled",
        '      add the annotation fabric.singleaxis.ai/inject: "python" to your agent\'s pod '
        "template (the SDK must be in its image) and roll it out yourself",
        "      fabric verify --kubernetes",
    ]


def _sensor_nodes(options: argparse.Namespace, environ: Mapping[str, str],
                  cluster: Cluster | None) -> list[str]:  # fmt: skip
    """``--host-node`` as given, else the nodes of the current kube context that can run
    the sensor, in the chart's own order (oldest first). ``FC-150`` when neither exists."""
    if options.host_node:
        return [str(node) for node in options.host_node]
    try:
        nodes = _cluster(environ, cluster).items("nodes")
    except (CliError, Forbidden):
        raise CliError([Finding("FC-150")], EXIT_USAGE) from None
    capable = sorted(
        (_kubeview._created(node), _kubeview._name(node))
        for node in nodes
        if _kubeview.node_sensor_reason(node) is None
    )
    if not capable:
        raise CliError([Finding("FC-150", "no node of the cluster can run it")], EXIT_USAGE)
    return [name for _, name in capable]


def _render(
    options: argparse.Namespace, environ: Mapping[str, str], tenant: str | None, chart: str,
    version: Sequence[str], wait_s: float, report: Report,
    which: Callable[..., str | None], cluster: Cluster | None,
) -> tuple[Report, list[str]]:  # fmt: skip
    """``--render DIR``: ``DIR/values.yaml`` and ``DIR/secrets/<namespace>/secret-*.yaml``
    (the same generator as ``fabric init --kubernetes --render``). Nothing is installed."""
    sensor = options.preset == "production-host-sensor"
    nodes = _sensor_nodes(options, environ, cluster) if sensor else []
    directory = _secrets.ensure_private_dir(Path(options.render))
    values_path = directory / "values.yaml"
    # JSON is YAML: Helm reads it, and it holds no secret.
    values_path.write_text(
        json.dumps(_values(options, tenant, nodes), indent=2, sort_keys=True) + "\n", "utf-8"
    )
    plan = _kube.Plan(
        namespace=options.namespace, release=options.release,
        production=options.preset != "local", injector=bool(options.injector),
        agents=tuple(_kube.AgentNamespace.parse(n) for n in options.agent_namespace or ()),
        host_sensor=sensor, host_nodes=tuple(nodes),
    )  # fmt: skip
    store = _kube.RenderStore(directory / "secrets")
    generator = _kube.Generator(plan, store)
    generator.run()
    report.findings.extend(generator.findings)
    report.findings.append(Finding("FC-143", str(directory)))
    command = ["helm", "upgrade", "--install", options.release, chart, *version, "--namespace",
               options.namespace, "--create-namespace", "--values", str(values_path)]  # fmt: skip
    for path in options.values or []:
        command += ["--values", str(path)]
    for value in options.set or []:
        command += ["--set", value]
    report.data = {"kubernetes": {
        "release": options.release, "namespace": options.namespace, "preset": options.preset,
        "chart": chart, "chart_version": version[1] if version else None,
        "agent_namespaces": list(options.agent_namespace or []),
        "injector": bool(options.injector), "rendered": str(directory),
        "values": str(values_path),
        "secrets": [outcome.to_json() for outcome in generator.outcomes],
    }}  # fmt: skip
    lines = [
        f"values: {values_path}",
        f"Secret manifests: {store.where} ({len(generator.outcomes)}; private, values are "
        "never printed)",
        f"apply the Secrets first: kubectl create -f {store.where} --recursive",
        "then: " + " ".join(command),
    ]
    _finish(report)
    return report, lines


def run_down(
    options: argparse.Namespace,
    environ: Mapping[str, str] | None = None,
    *,
    runner: Callable[..., Any] = subprocess.run,
    which: Callable[..., str | None] = shutil.which,
    cluster: Cluster | None = None,
) -> tuple[Report, list[str]]:
    """``fabric down --kubernetes``: one ``helm uninstall`` of the Fabric release. The
    generated Secrets are kept (a new install keeps every key and id) unless ``--purge``,
    which deletes exactly the Secrets labelled as generated by Fabric for this release."""
    environ = os.environ if environ is None else environ
    _kube.check_namespace(options.namespace, "release namespace")
    _kube.check_namespace(options.release, "release name")
    helm = _helm(environ, which)
    namespaces = [options.namespace]
    kubectl: str | None = None
    if options.purge:
        # Read which namespaces hold generated Secrets before the release is gone.
        found = _cluster(environ, cluster)
        kubectl = found.kubectl
        with contextlib.suppress(CliError):
            install = _kubeview.find_install(found, options.namespace)
            namespaces += [str(agent.get("name")) for agent in install.agents]
    report = Report("down")
    result = _run(runner, [helm, "uninstall", options.release, "--namespace", options.namespace,
                           "--wait"], environ, DEFAULT_HELM_WAIT_S)  # fmt: skip
    missing = "not found" in (result.stderr or "")
    if result.returncode != 0 and not (missing and options.purge):
        if missing:
            raise CliError(
                [Finding("FC-122", f"release {options.release} in namespace {options.namespace}")],
                EXIT_FINDINGS,
            )
        raise CliError([Finding("FC-123", _tail(result.stderr))], EXIT_FINDINGS)
    report.data = {"kubernetes": {"release": options.release, "namespace": options.namespace,
                                  "purged": False}}  # fmt: skip
    where = f"release {options.release}, namespace {options.namespace}"
    if not options.purge or kubectl is None:
        report.findings.append(Finding("FC-149", where))
        return report, [f"removed {where}; the generated Secrets are kept"]
    for namespace in dict.fromkeys(namespaces):
        deleted = _run(
            runner,
            [kubectl, "delete", "secret", "--namespace", namespace, "--selector",
             _GENERATED_SELECTOR + options.release, "--ignore-not-found"],
            environ, 60.0,
        )  # fmt: skip
        if deleted.returncode != 0:
            raise CliError(
                [Finding("FC-102", f"deleting Fabric's Secrets in {namespace}: "
                         + _tail(deleted.stderr, 1))],
                EXIT_FINDINGS,
            )  # fmt: skip
    report.data["kubernetes"]["purged"] = True
    report.data["kubernetes"]["namespaces"] = list(dict.fromkeys(namespaces))
    report.findings.append(Finding("FC-144", where))
    return report, [f"removed {where} and the Secrets Fabric generated in "
                    + ", ".join(dict.fromkeys(namespaces))]  # fmt: skip


