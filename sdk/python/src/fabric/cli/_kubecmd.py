def _cluster(environ: Mapping[str, str], cluster: Cluster | None) -> Cluster:
    """kubectl against the current kube context, after one call that proves the API
    server answers (``FC-120`` without kubectl, ``FC-103`` when it does not answer)."""
    found = cluster or Cluster(environ=environ)
    found.version()
    return found


def _finish(report: Report, *, strict: bool = False) -> None:
    failing = {"error", "warning"} if strict else {"error"}
    report.exit_code = (
        EXIT_FINDINGS if any(f.severity in failing for f in report.findings) else EXIT_OK
    )


