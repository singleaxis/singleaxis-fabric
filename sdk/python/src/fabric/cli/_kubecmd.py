def run_plan(
    options: argparse.Namespace,
    environ: Mapping[str, str] | None = None,
    *,
    cluster: Cluster | None = None,
) -> tuple[Report, list[str]]:
    """``fabric plan --kubernetes``: read-only; writes and starts nothing."""
    environ = os.environ if environ is None else environ
    cluster = _cluster(environ, cluster)
    view = _kubeview.View()
    report = Report("plan", findings=view.findings)
    version = cluster.version()
    server = str((version.get("serverVersion") or {}).get("gitVersion") or "unknown")
    lines = [f"shape: kubernetes   server: {server}"]
    nodes: list[dict[str, Any]] = []
    try:
        nodes = cluster.items("nodes")
    except Forbidden as exc:
        view.skipped("nodes", exc)
    capable, node_rows = [], []
    for node in nodes:
        info = (node.get("status") or {}).get("nodeInfo") or {}
        name = _kubeview._name(node)
        reason = _kubeview.node_sensor_reason(node)
        if reason is None:
            capable.append(name)
        node_rows.append({
            "name": name, "kernel": info.get("kernelVersion"), "os": info.get("osImage"),
            "runtime": info.get("containerRuntimeVersion"), "kubelet": info.get("kubeletVersion"),
            "host_sensor": "can run" if reason is None else f"cannot run: {reason}",
        })  # fmt: skip
        lines.append(
            f"  node {name}: kernel {info.get('kernelVersion', '?')}, "
            f"{info.get('containerRuntimeVersion', '?')}; host sensor "
            + ("can run" if reason is None else f"cannot run ({reason})")
        )
    cgroups = _kubelet_cgroups(cluster, capable[:1])
    sandboxes = _kubeview.sandbox_runtime_classes(cluster, view)
    policies = _serves_network_policies(cluster)
    install: _kubeview.Install | None = None
    try:
        install = _kubeview.find_install(cluster, getattr(options, "namespace", None))
    except CliError as exc:
        if [f.id for f in exc.findings] != ["FC-122"]:
            raise
    lines.append("")
    rows = _plan_rows(install, capable, nodes, sandboxes, cgroups, policies)
    lines.extend(f"  {question:<38} {state:<12} {note}" for question, state, note in rows)
    lines.append("")
    if install is None:
        preset = "production-host-sensor" if capable else "production"
        lines.append(
            "next: fabric up --kubernetes --agent-namespace NAMESPACE --injector   (a trial "
            f"Node; for production: helm install with --set preset={preset}, "
            "docs/get-started/kubernetes.md)"
        )
    else:
        lines.append(f"installed: {install.summary()}")
        lines.append("next: fabric verify --kubernetes")
    for name, handler in sandboxes:
        view.findings.append(Finding("FC-138", f"{name} (handler {handler})"))
    view.findings.append(Finding("FC-148", f"{len(nodes)} node(s)"))
    report.data = {
        "shape": "kubernetes", "server_version": server, "nodes": node_rows,
        "runtime_classes": [{"name": n, "handler": h} for n, h in sandboxes],
        "network_policy_api": policies, "kubelet_cgroups": cgroups,
        "release": None if install is None else {
            "name": install.release, "namespace": install.namespace,
            "preset": install.info.get("preset")},
        "coverage": [{"row": q, "state": s, "note": n} for q, s, n in rows],
    }  # fmt: skip
    _finish(report)
    return report, lines


def _kubelet_cgroups(cluster: Cluster, nodes: Sequence[str]) -> dict[str, Any] | None:
    """The kubelet's cgroup driver and root of one node, when the identity may read the
    node's ``configz`` (nodes/proxy); None otherwise: the sensor finds the layout itself."""
    for node in nodes:
        try:
            config = cluster.raw(f"/api/v1/nodes/{node}/proxy/configz")
        except (CliError, Forbidden, _kubeview.NotFound):
            return None
        kubelet = (config or {}).get("kubeletconfig") if isinstance(config, dict) else None
        if isinstance(kubelet, dict):
            return {"node": node, "driver": kubelet.get("cgroupDriver"),
                    "root": kubelet.get("cgroupRoot") or "/"}  # fmt: skip
    return None


def _serves_network_policies(cluster: Cluster) -> bool | None:
    try:
        resources = cluster.raw("/apis/networking.k8s.io/v1")
    except (CliError, Forbidden, _kubeview.NotFound):
        return None
    listed = (resources or {}).get("resources") if isinstance(resources, dict) else None
    return any(r.get("name") == "networkpolicies" for r in listed or [])


def _plan_rows(
    install: _kubeview.Install | None, capable: Sequence[str], nodes: Sequence[Any],
    sandboxes: Sequence[tuple[str, str]], cgroups: Mapping[str, Any] | None,
    policies: bool | None,
) -> list[tuple[str, str, str]]:  # fmt: skip
    """The predicted coverage rows of a cluster (§12.3), from what was read."""
    injector = bool(install and install.injector.get("enabled"))
    sensor = bool(install and install.sensor.get("enabled"))
    rows = [
        (
            "model calls (requests and responses)",
            "recorded" if injector else "fix",
            "pods annotated fabric.singleaxis.ai/inject: python, with the SDK in their image"
            if injector
            else "--set injector.enabled=true and agentNamespaces; then annotate the agent's pods",
        ),
        ("tool calls and results", "recorded" if injector else "fix", "parsed from model bodies"),
        ("commands the agent runs", "fix", "--set injector.env.FABRIC_WIRE_EXEC=1"),
    ]
    layout = (
        f"kubelet cgroup driver {cgroups.get('driver')}, root {cgroups.get('root')}"
        if cgroups
        else "the sensor finds the kubelet's pod cgroups itself"
    )
    if not capable:
        rows.append(("host evidence (kernel sensor)", "invisible",
                     "no node of this cluster can run the host sensor"))  # fmt: skip
    elif sensor:
        rows.append(("host evidence (kernel sensor)", "recorded",
                     f"{len(capable)} of {len(nodes)} node(s); {layout}"))  # fmt: skip
    else:
        rows.append(("host evidence (kernel sensor)", "fix",
                     f"--set preset=production-host-sensor ({len(capable)} of {len(nodes)} "
                     f"node(s) can run it; {layout})"))  # fmt: skip
    for name, handler in sandboxes:
        rows.append(
            (
                f"pods under RuntimeClass {name}",
                "invisible",
                f"unsupported_runtime: handler {handler} keeps system calls from the "
                "node's kernel; wire capture in the agent still records model calls",
            )
        )
    if policies is False:
        rows.append(("network isolation of the Node", "invisible",
                     "this cluster serves no NetworkPolicy API"))  # fmt: skip
    rows.append(("end user and session", "needs code",
                 "with fabric.wire.run(session_id=..., user_id=...)"))  # fmt: skip
    return rows


