def health_probe(port: int, timeout: float = 5.0) -> bool:
    """The Node's health endpoint through the forwarded loopback port."""
    connection = http.client.HTTPConnection("127.0.0.1", port, timeout=timeout)
    try:
        connection.request("GET", "/")
        return connection.getresponse().status == http.client.OK
    except (OSError, http.client.HTTPException):
        return False
    finally:
        connection.close()


def run_doctor(
    options: argparse.Namespace,
    environ: Mapping[str, str] | None = None,
    *,
    cluster: Cluster | None = None,
    probe: Callable[[int], bool] = health_probe,
) -> tuple[Report, list[str]]:
    """``fabric doctor --kubernetes``: the checks of ``verify --kubernetes`` without a
    canary or a readback, plus the pods whose spool is lost when they exit. Never changes
    anything."""
    environ = os.environ if environ is None else environ
    cluster = _cluster(environ, cluster)
    install = _kubeview.find_install(cluster, options.namespace)
    view = _kubeview.gather(cluster, install, probe=probe, one_shot=True)
    view.data.pop("agent_pods", None)
    problems = [f for f in view.findings if f.severity in ("error", "warning")]
    if not problems:
        view.findings.append(Finding("FC-097"))
    report = Report("doctor", findings=view.findings)
    report.data = {"kubernetes": view.data, "problems": len(problems)}
    _finish(report)
    return report, view.lines


def _id_key(cluster: Cluster, install: _kubeview.Install, view: _kubeview.View) -> bytes | None:
    """The key the records' pseudonyms are made with, for the reader: the release's
    shared id key with the host sensor, else the first agent namespace's. Read from its
    Secret into this process only; never printed or written."""
    sources: list[tuple[str, str, str]] = []
    if install.sensor.get("enabled") and install.sensor.get("idKeySecret"):
        sources.append((install.namespace, str(install.sensor["idKeySecret"]), "id_key"))
    sources += [(str(a.get("name")), str(a.get("secret") or "fabric-agent"), "id.key")
                for a in install.agents]  # fmt: skip
    for namespace, name, key in sources:
        try:
            value = cluster.secret_value(namespace, name, key)
        except Forbidden as exc:
            view.skipped(f"Secret {namespace}/{name} (the reader's id key)", exc)
            continue
        if value:
            return value[:-1] if value.endswith(b"\n") else value
    return None


def _service_ip(cluster: Cluster, host: str, cache: dict[str, str | None]) -> str | None:
    """The address a model host of a pod's endpoint list is reached at: an IP literal as
    it is, a cluster Service name by its ClusterIP (read from the API, never resolved)."""
    if host in cache:
        return cache[host]
    found: str | None = None
    try:
        found = str(ipaddress.ip_address(host))
    except ValueError:
        match = _SERVICE_HOST.match(host)
        if match:
            with contextlib.suppress(Forbidden, CliError):
                service = cluster.find("service", match["name"], match["ns"])
                address = ((service or {}).get("spec") or {}).get("clusterIP")
                found = str(address) if address and address != "None" else None
    cache[host] = found
    return found


def reader_peers(
    cluster: Cluster, install: _kubeview.Install, pods: Sequence[Mapping[str, Any]],
    node_pods: Sequence[Mapping[str, Any]],
) -> tuple[dict[str, list[str]], list[str]]:  # fmt: skip
    """§13.4: the addresses the reader needs to tell an agent's own connections from
    unexplained ones, read from the cluster instead of typed by the user. Returns the
    model endpoints' addresses by configured endpoint id (from the injected pods'
    ``FABRIC_WIRE_ENDPOINTS``) and the known infrastructure peers (the Node's Service and
    pods, the cluster DNS)."""
    known: list[str] = []
    selector = (f"app.kubernetes.io/name={_kubeview.NODE_APP},"
                f"app.kubernetes.io/instance={install.release}")  # fmt: skip
    for namespace, label in ((install.namespace, selector), ("kube-system", "k8s-app=kube-dns")):
        with contextlib.suppress(Forbidden, CliError):
            for service in cluster.items("services", namespace, label):
                address = (service.get("spec") or {}).get("clusterIP")
                if address and address != "None":
                    known.append(str(address))
    known += [str(ip) for pod in node_pods if (ip := (pod.get("status") or {}).get("podIP"))]
    endpoints: dict[str, list[str]] = {}
    cache: dict[str, str | None] = {}
    for pod in pods:
        for container in (pod.get("spec") or {}).get("containers") or []:
            for entry in container.get("env") or []:
                if entry.get("name") != "FABRIC_WIRE_ENDPOINTS" or not entry.get("value"):
                    continue
                try:
                    matchers = json.loads(entry["value"])
                except ValueError:
                    continue
                for matcher in matchers if isinstance(matchers, list) else []:
                    if not isinstance(matcher, dict) or not matcher.get("endpoint_id"):
                        continue
                    for host in matcher.get("hosts") or []:
                        address = _service_ip(cluster, str(host), cache)
                        if address:
                            endpoints.setdefault(str(matcher["endpoint_id"]), []).append(address)
    return ({name: list(dict.fromkeys(ips)) for name, ips in endpoints.items()},
            list(dict.fromkeys(known)))  # fmt: skip


def _read_run(
    cluster: Cluster, install: _kubeview.Install, view: _kubeview.View,
    options: argparse.Namespace, node_pods: Sequence[Mapping[str, Any]],
    pods: Sequence[Mapping[str, Any]], environ: Mapping[str, str],
) -> dict[str, Any] | None:  # fmt: skip
    """§5.6 steps 5 and 6 for a cluster: the reader over the destination's export
    (``--spans``), the named run or the one that started last, judged, and its observed
    coverage with the host sensor's records joined."""
    from .._sequence import label_pseudonym  # noqa: PLC0415 - reader-only imports
    from ..reconstruct._attribute import ActionReader  # noqa: PLC0415
    from ..reconstruct._host import HostPlan, peer_id  # noqa: PLC0415
    from ..reconstruct._ids import report_run_id  # noqa: PLC0415
    from ..reconstruct._inputs import ReconstructInputError  # noqa: PLC0415
    from ..reconstruct._report import COMPLETE_VERDICTS, EXIT_RUN_STATES  # noqa: PLC0415
    from ..reconstruct._verify import reconstruct  # noqa: PLC0415
    from . import _read  # noqa: PLC0415

    key = _id_key(cluster, install, view)
    joiner = None
    if key is not None:
        endpoints, known = reader_peers(cluster, install, pods, node_pods)
        keyed: dict[str, list[str]] = {}
        for name, addresses in endpoints.items():
            emitted = name if _EMITTED_ENDPOINT.match(name) else label_pseudonym("lbl-", name, key)
            keyed[emitted] = [p for a in addresses if (p := peer_id(a, key)) is not None]
        joiner = HostPlan(
            endpoint_peers=keyed,
            known_peers=[p for a in known if (p := peer_id(a, key)) is not None],
        )
    reader = ActionReader(every_run=True, keep_runs=True, id_key=key, host_joiner=joiner)
    store, tenant = content_store(install, view, environ)
    try:
        document = reconstruct(
            [str(options.spans)], id_key=key, actions=reader, store=store, tenant_id=tenant,
            profile="production" if install.production else None,
            # --spans names the destination the operator chose for this Node (§5.6).
            trusted_source=install.production,
        )  # fmt: skip
    except ReconstructInputError as exc:
        from ..reconstruct._inputs import ACCEPTED_INPUTS  # noqa: PLC0415

        text = str(exc)
        view.findings.append(
            Finding("FC-073", text if ACCEPTED_INPUTS in text
                    else f"{text}; accepted: {ACCEPTED_INPUTS}")
        )  # fmt: skip
        return None
    wanted = report_run_id(options.run, key) if options.run else ended_run_id(document)
    run = next((r for r in document.get("runs") or [] if r["run_id"] == wanted), None)
    if run is None:
        view.findings.append(
            Finding("FC-067", f"{options.run or 'no run with a model call'} in {options.spans} "
                    f"({len(document.get('runs') or [])} run(s) there)")
        )  # fmt: skip
        return None
    chains = {name: chain.get("verdict") for name, chain in (run.get("chains") or {}).items()}
    exchanges = int(run["counts"]["exchanges"])
    view.lines.append(f"run {run['run_id']}: {run['verdict']}, {exchanges} exchange(s)")
    view.lines.append("  " + "   ".join(f"{name}: {verdict}" for name, verdict in chains.items()))
    state = run.get("run_state")
    complete = run["verdict"] in COMPLETE_VERDICTS and state in EXIT_RUN_STATES
    if complete and chains.get("decisions") == "complete":
        view.findings.append(
            Finding("FC-069", f"{run['run_id']}: {exchanges} exchange(s), decisions: complete")
        )
    else:
        reasons = "; ".join(_read.words(r) for r in _read.run_reasons(run))
        view.findings.append(
            Finding("FC-068", (f"{run['run_id']}: {run['verdict']}"
                               + (f" ({state})" if state not in EXIT_RUN_STATES else "")
                               + f", decisions {chains.get('decisions', 'not observed')}"
                               + (f" - {reasons}" if reasons else ""))[:4000])
        )  # fmt: skip
    rows = _coverage(install, run, chains, exchanges)
    sensor = bool(install.sensor.get("enabled"))
    if sensor and chains.get("corroboration") in (None, "not_observed"):
        view.findings.append(Finding("FC-141", str(run["run_id"])))
    view.lines.append("coverage (observed):")
    view.lines.extend(row.line() for row in rows)
    return {
        "run_id": run["run_id"], "verdict": run["verdict"], "exchanges": exchanges,
        "chains": chains,
        "corroboration_reasons": list((run.get("chains") or {}).get("corroboration", {})
                                      .get("reasons") or []),
        "coverage": [row.to_json() for row in rows],
    }  # fmt: skip


#: The AWS configuration that names an S3 endpoint for this workstation (botocore reads
#: them when no endpoint is passed): it wins over the endpoint the Node writes to, which
#: may be an address only the cluster reaches.
_AWS_ENDPOINT_VARIABLES = ("AWS_ENDPOINT_URL_S3", "AWS_ENDPOINT_URL")


def content_store(install: _kubeview.Install, view: _kubeview.View,
                  environ: Mapping[str, str]) -> tuple[Any | None, str | None]:  # fmt: skip
    """The release's content store, opened with this workstation's AWS configuration (the
    default credential chain, ``AWS_CA_BUNDLE``, ``AWS_ENDPOINT_URL_S3``), and its tenant:
    the model bodies the decisions chain is verified against (§5.6 step 5). ``FC-154``
    when the release keeps none this workstation can read, ``FC-153`` without boto3."""
    store = install.node.get("contentStore") or {}
    backend = str(store.get("backend") or "")
    tenant = str(install.info.get("tenantId") or "") or next(
        (str(a.get("tenantId")) for a in install.agents if a.get("tenantId")), None
    )
    if backend != "s3" or not store.get("bucket") or not tenant:
        why = (f"content backend {backend}: the bodies are on the Node's volume" if backend
               else "content delivery is off (otel-collector.content.enabled=false)")  # fmt: skip
        view.findings.append(Finding("FC-154", why))
        return None, None
    from ..content_store.s3 import S3ContentStore  # noqa: PLC0415

    own_endpoint = any((environ.get(name) or "").strip() for name in _AWS_ENDPOINT_VARIABLES)
    prefix = str(store.get("prefix") or "").strip("/")
    try:
        opened = S3ContentStore(
            bucket=str(store["bucket"]),
            prefix=f"{prefix}/" if prefix else "fabric/content/",
            tenant_id=tenant,
            region_name=str(store.get("region") or "") or None,
            endpoint_url=None if own_endpoint else (str(store.get("endpoint") or "") or None),
            addressing_style="path" if store.get("pathStyle") else None,
        )
        opened.ensure_client()
    except ImportError:
        view.findings.append(Finding("FC-153", f"s3://{store['bucket']}"))
        return None, None
    except ValueError:
        # Fixed text: a constructor message can echo a bucket, prefix or credential.
        view.findings.append(Finding("FC-154", "the release's content store settings are invalid"))
        return None, None
    view.lines.append(f"content store: s3://{store['bucket']}/{prefix} (tenant {tenant})")
    return opened, tenant


def ended_run_id(document: Mapping[str, Any]) -> str | None:
    """The run to judge without ``RUN``: the newest run (by its first model exchange) whose
    process has ended, so an agent that runs in a loop is never judged mid-run; the
    newest run when none has ended yet."""
    from ..reconstruct._report import EXIT_RUN_STATES  # noqa: PLC0415
    from ..reconstruct._select import latest_run_id, run_start_ns  # noqa: PLC0415

    ended = [(start, str(run["run_id"])) for run in document.get("runs") or []
             if run.get("run_state") in EXIT_RUN_STATES
             and (start := run_start_ns(run)) is not None]  # fmt: skip
    return max(ended)[1] if ended else latest_run_id(document)


def _coverage(install: _kubeview.Install, run: Mapping[str, Any],
              chains: Mapping[str, Any], exchanges: int) -> list[Any]:  # fmt: skip
    from . import _read  # noqa: PLC0415

    row = _read.Row
    rows = [
        row("model calls (requests and responses)", "recorded" if exchanges else "not observed",
            f"{exchanges} exchange(s)" if exchanges else "no model call was recorded"),
        row("tool calls and results", _read._state(chains.get("decisions")),
            "parsed from the model bodies" if chains.get("decisions") else "no model call"),
    ]  # fmt: skip
    effects = (run.get("chains") or {}).get("effects") or {}
    if effects.get("verdict") in (None, "not_observed"):
        rows.append(
            row(
                "commands the agent ran",
                "fix",
                "--set injector.env.FABRIC_WIRE_EXEC=1 (helm upgrade), then your rollout",
            )
        )
    else:
        rows.append(row("commands the agent ran", _read._state(effects.get("verdict")),
                        "exec hook"))  # fmt: skip
    corroboration = (run.get("chains") or {}).get("corroboration") or {}
    if not install.sensor.get("enabled"):
        rows.append(
            row(
                "host evidence (kernel sensor)",
                "fix",
                "--set preset=production-host-sensor (hostSensor.enabled=true)",
            )
        )
    else:
        reasons = "; ".join(_read.words(str(r)) for r in corroboration.get("reasons") or []
                            if corroboration.get("verdict") != "complete")  # fmt: skip
        rows.append(row("host evidence (kernel sensor)",
                        _read._state(corroboration.get("verdict")),
                        reasons or "host sensor records joined to this run"))  # fmt: skip
    rows.append(row("end user and session", "needs code",
                    "with fabric.wire.run(session_id=..., user_id=...)"))  # fmt: skip
    return rows


def run_canary(cluster: Cluster, install: _kubeview.Install, environ: Mapping[str, str],
               label: str) -> dict[str, Any]:  # fmt: skip
    """§10.6: the canary through a port-forward to the Node's OTLP/HTTP port, opened for
    this one exchange and closed. Its environment names only the forwarded port and the
    release's CA certificate (public material, written to a private temporary file)."""
    try:
        ca = cluster.secret_value(install.namespace, str(install.info.get("caSecret")), "ca.crt")
    except Forbidden:
        ca = None
    if not ca:
        return {"installed": False, "error": "the release's CA certificate could not be read"}
    service = f"svc/{install.node.get('service')}"
    with tempfile.TemporaryDirectory(prefix="fabric-canary-") as directory:
        ca_file = Path(directory) / "ca.crt"
        ca_file.write_bytes(ca)
        with cluster.port_forward(install.namespace, service, 4318) as local:
            env = {
                "PATH": environ.get("PATH", os.defpath),
                "HOME": environ.get("HOME", directory),
                "FABRIC_TENANT_ID": str(install.info.get("tenantId") or "default"),
                "FABRIC_AGENT_ID": "fabric-canary",
                "FABRIC_OTLP_ENDPOINT": f"https://localhost:{local}",
                "FABRIC_OTLP_CERTIFICATE": str(ca_file),
                "FABRIC_WIRE_SPOOL_DIR": str(Path(directory) / "spool"),
            }
            try:
                result = subprocess.run(  # noqa: S603 - this interpreter, this package
                    [sys.executable, "-m", "fabric.cli._canary", label,
                     str(Path(directory) / "status.json")],
                    env=env, capture_output=True, text=True, timeout=CANARY_TIMEOUT_S,
                    check=False, stdin=subprocess.DEVNULL, cwd=directory,
                )  # fmt: skip
                lines = result.stdout.strip().splitlines()
                answer = json.loads(lines[-1]) if lines else {}
            except subprocess.TimeoutExpired:
                return {"installed": False, "error": f"no answer in {CANARY_TIMEOUT_S:g} s"}
            except (OSError, ValueError):
                return {"installed": False, "error": "could not be started"}
    return answer if isinstance(answer, dict) else {"installed": False, "error": "no answer"}


def _canary(
    cluster: Cluster,
    install: _kubeview.Install,
    environ: Mapping[str, str],
    view: _kubeview.View,
    canary: Callable[..., dict[str, Any]],
) -> dict[str, Any]:
    if install.production:
        view.findings.append(Finding("FC-142"))
        view.lines.append("canary: not sent (a production Node binds every source; see FC-142)")
        return {"sent": False}
    if not (view.data.get("node") or {}).get("ready"):
        view.lines.append("canary: not sent (the Node has no ready pod)")
        return {"sent": False}
    label = f"canary-{int(time.time())}-{_random.token_hex(3)}"
    try:
        answer = canary(cluster, install, environ, label)
    except CliError as exc:
        view.findings.extend(exc.findings)
        return {"sent": False}
    data = {"sent": True, "label": label, "installed": bool(answer.get("installed")),
            "delivered": bool(answer.get("delivered"))}  # fmt: skip
    if not answer.get("installed"):
        from . import _verify  # noqa: PLC0415 - the SDK's own reason, worded once

        view.findings.append(_verify._canary_failure(answer))
        view.lines.append("canary: capture did not install (see the finding)")
    elif not answer.get("delivered"):
        view.findings.append(
            Finding("FC-063", "the Node did not accept the records through the port-forward; a "
                    "Node certificate made before this release does not name localhost")
        )  # fmt: skip
        view.lines.append("canary: recorded, but the Node did not take the records")
    else:
        view.lines.append("canary: recorded and accepted by the Node")
    return data


#: How long ``verify --kubernetes --spans`` waits for a judged run when ``--wait`` is not
#: given: the operator's own rollout comes first, then a run, then the destination.
KUBERNETES_WAIT_S = 180.0
_POLL_S = 5.0


#: Findings that may clear on their own while a release starts (a Node pod not ready
#: yet, a sensor that exported before the Node listened): verify waits them out.
_TRANSIENT = frozenset({"FC-126", "FC-133", "FC-135"})


def _settled(found: dict[str, Any] | None, findings: Sequence[Finding], sensor: bool) -> bool:
    """A judged run that needs no more waiting: complete with decisions complete, no
    transient problem left and, with the host sensor installed, corroborated."""
    ids = {f.id for f in findings}
    if found is None or "FC-069" not in ids or ids & _TRANSIENT:
        return False
    return not sensor or found["chains"].get("corroboration") == "complete"


def run_verify(
    options: argparse.Namespace,
    environ: Mapping[str, str] | None = None,
    *,
    cluster: Cluster | None = None,
    probe: Callable[[int], bool] = health_probe,
    canary: Callable[..., dict[str, Any]] = run_canary,
    sleep: Callable[[float], None] = time.sleep,
    clock: Callable[[], float] = time.monotonic,
) -> tuple[Report, list[str]]:
    """``fabric verify --kubernetes``. With ``--spans``, §5.6 step 4 for a cluster: the
    checks and the readback are repeated (bounded by ``--wait``) until the run is judged
    complete and, with the sensor, corroborated, with nothing transient left; the last
    attempt is reported. An unreadable export is reported at once."""
    from ._args import DEFAULT_WAIT_S  # noqa: PLC0415

    environ = os.environ if environ is None else environ
    cluster = _cluster(environ, cluster)
    install = _kubeview.find_install(cluster, options.namespace)
    reading = bool(options.spans) and not options.canary_only
    wait = KUBERNETES_WAIT_S if options.wait == DEFAULT_WAIT_S else float(options.wait)
    deadline = clock() + wait
    sensor = bool(install.sensor.get("enabled"))
    while True:
        view = _kubeview.gather(cluster, install, probe=probe)
        pods = view.data.pop("agent_pods", [])
        attempt = _kubeview.View()
        found: dict[str, Any] | None = None
        if reading:
            node_pods: list[dict[str, Any]] = []
            with contextlib.suppress(Forbidden, CliError):
                node_pods = _kubeview.node_pods(cluster, install)
            found = _read_run(cluster, install, attempt, options, node_pods, pods, environ)
        unreadable = any(f.id in ("FC-073", "FC-153") for f in attempt.findings)
        if (not reading or unreadable or clock() >= deadline
                or _settled(found, [*view.findings, *attempt.findings], sensor)):  # fmt: skip
            break
        sleep(min(_POLL_S, max(deadline - clock(), 0.0)))
    report = Report("verify", findings=view.findings)
    report.data = {"kubernetes": view.data}
    report.data["canary"] = _canary(cluster, install, environ, view, canary)
    if reading:
        view.findings.extend(attempt.findings)
        view.lines.extend(attempt.lines)
        report.data["run"] = found
    elif not options.canary_only:
        view.findings.append(
            Finding("FC-074", "the Node sends records to the destination you configured: "
                    "pass --spans PATH with its export to read the run back")
        )  # fmt: skip
    _finish(report, strict=options.strict)
    view.lines.append(
        "result: "
        + ("no problem found" if report.exit_code == EXIT_OK else "see the findings below")
    )
    return report, view.lines


