var pseudonymPatterns = map[string]*regexp.Regexp{}

// pseudonymPattern is the keyed-pseudonym form prefix- + 32 lowercase hex
// (spec 049 §2.9); compiled once per prefix at package initialization.
func pseudonymPattern(prefix string) *regexp.Regexp {
	if pattern, ok := pseudonymPatterns[prefix]; ok {
		return pattern
	}
	pattern := regexp.MustCompile(`^` + regexp.QuoteMeta(prefix) + `-[0-9a-f]{32}$`)
	pseudonymPatterns[prefix] = pattern
	return pattern
}

