// isRFC3339 admits an RFC 3339 date-time with at most nanosecond precision.
func isRFC3339(value pcommon.Value) bool {
	if value.Type() != pcommon.ValueTypeStr || !rfc3339Pattern.MatchString(value.Str()) {
		return false
	}
	_, err := time.Parse(time.RFC3339Nano, value.Str())
	return err == nil
}

var rfc3339Pattern = regexp.MustCompile(`^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]{1,9})?(Z|[+-][0-9]{2}:[0-9]{2})$`)

// matchesInt64 is matches plus a bound: each named decimal group that took
// part in the match fits a signed 64-bit integer (epochs are 63-bit values).
func matchesInt64(pattern *regexp.Regexp, groups ...string) func(pcommon.Value) bool {
	return func(value pcommon.Value) bool {
		if value.Type() != pcommon.ValueTypeStr {
			return false
		}
		match := pattern.FindStringSubmatch(value.Str())
		if match == nil {
			return false
		}
		for _, group := range groups {
			text := match[pattern.SubexpIndex(group)]
			if text == "" {
				continue
			}
			if _, err := strconv.ParseInt(text, 10, 64); err != nil {
				return false
			}
		}
		return true
	}
}

// sliceOf admits a slice of minItems..maxItems elements that each pass item,
// distinct when unique is set.
func sliceOf(minItems, maxItems int, unique bool, item func(pcommon.Value) bool) func(pcommon.Value) bool {
	return func(value pcommon.Value) bool {
		if value.Type() != pcommon.ValueTypeSlice {
			return false
		}
		slice := value.Slice()
		if slice.Len() < minItems || slice.Len() > maxItems {
			return false
		}
		seen := map[string]struct{}{}
		for i := 0; i < slice.Len(); i++ {
			element := slice.At(i)
			if !item(element) {
				return false
			}
			if unique {
				text := element.AsString()
				if _, dup := seen[text]; dup {
					return false
				}
				seen[text] = struct{}{}
			}
		}
		return true
	}
}

// validPredecessorLabels applies capture_labels (spec 048 J1) to the source
// id inside each fabric.run.predecessors entry: by default the Node admits it
// only in its s-<32 hex> form, as it does fabric.source_id itself.
func (g *guard) validPredecessorLabels(value pcommon.Value) bool {
	if g.clearLabels() {
		return true
	}
	slice := value.Slice()
	group := predecessorPattern.SubexpIndex("source")
	for i := 0; i < slice.Len(); i++ {
		match := predecessorPattern.FindStringSubmatch(slice.At(i).Str())
		if source := match[group]; source != "" && !sourcePseudonymPattern.MatchString(source) {
			return false
		}
	}
	return true
}

// validCoverageValue closes a spec 049 key's value; ok is false when the key
// is not a coverage key.
func (g *guard) validCoverageValue(key string, value pcommon.Value) (valid, ok bool) {
	validate, ok := coverageKeyValidators[key]
	if !ok {
		return false, false
	}
	if _, keeps := clearIdentityKeys[key]; keeps && g.cfg.IdentityMode == identityModeClear {
		// identity_mode clear keeps the pre-049 admission (spec 049 §2.9
		// rule 7): the generic metadata checks of filterAttributes still apply.
		return true, true
	}
	if !validate(value) {
		return false, true
	}
	if key == "fabric.run.predecessors" {
		return g.validPredecessorLabels(value), true
	}
	if _, operator := operatorLabelKeys[key]; operator && !g.clearLabels() {
		return labelPseudonymPattern.MatchString(value.Str()), true
	}
	return true, true
}

