// Generates the TypeScript wire core's contract tables (spec 055 §3.4, §4.7) from the
// contracts, as sdk/python/scripts/sync_contract_data.py does for Python:
//
//   src/wire/endpoint-table.generated.ts   contracts/providers/v1/builtin-endpoints.json
//   src/wire/catalogue.generated.ts        contracts/diagnostics/v1/messages-v1.json (FW- ids)
//   src/wire/telemetry-keys.generated.ts   contracts/coverage/v1/registry/telemetry-keys-v1.json
//                                          and capture-points-v1.json (point kinds)
//
// Usage: node scripts/typescript/sync-contract-data.mjs [--check]
// --check writes nothing and exits 1 when a generated file differs from its contract.
// The generated files are never edited by hand; sdk/typescript/test/wire tests keep each
// equal to its contract.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(ROOT, "sdk", "typescript", "src", "wire");
const SCRIPT = "scripts/typescript/sync-contract-data.mjs";
const HEADER =
    "// Copyright 2026 AI5Labs Research OPC Private Limited\n" +
    "// SPDX-License-Identifier: Apache-2.0\n" +
    `// Code generated by ${SCRIPT}. DO NOT EDIT.\n`;

/** JSON with exact integers: an integer above 2^53 is read as a bigint, never rounded. */
function readJson(path) {
    const text = readFileSync(join(ROOT, path), "utf8");
    return JSON.parse(text, (_key, value, context) =>
        typeof value === "number" &&
        Number.isInteger(value) &&
        !Number.isSafeInteger(value)
            ? BigInt(context.source)
            : value,
    );
}

/** A TypeScript literal of a JSON value (bigints as `123n`). */
function literal(value) {
    const marks = [];
    const text = JSON.stringify(
        value,
        (_key, item) => {
            if (typeof item === "bigint") {
                marks.push(item);
                return `__BIGINT_${marks.length - 1}__`;
            }
            return item;
        },
        2,
    );
    return text.replace(
        /"__BIGINT_(\d+)__"/g,
        (_m, index) => `${marks[Number(index)]}n`,
    );
}

function endpointTable() {
    const source = "contracts/providers/v1/builtin-endpoints.json";
    const table = readJson(source);
    return (
        HEADER +
        `// Source: ${source} (spec 058 §8.1). A test keeps it equal to the contract.\n\n` +
        `/** The built-in model endpoint table, as Python's wire/_endpoint_table.py. */\n` +
        `export const ENDPOINT_TABLE = ${literal(table)} as const;\n`
    );
}

function catalogue() {
    const source = "contracts/diagnostics/v1/messages-v1.json";
    const doc = readJson(source);
    const entries = doc.messages.filter((m) => m.id.startsWith("FW-"));
    const union = (ids) =>
        ids.length === 0
            ? "never"
            : ids.map((id) => JSON.stringify(id)).join(" | ");
    const ts = entries
        .filter(
            (m) =>
                (m.sdk ?? ["python"]).includes("typescript") &&
                m.retired !== true,
        )
        .map((m) => m.id);
    return (
        HEADER +
        `// Source: ${source} (spec 058 §13.1, spec 055 §4.7): the FW- entries, Python's and\n` +
        "// TypeScript's. TypeScript emits these ids and has no message table of its own.\n\n" +
        'import type { CatalogueEntry } from "./types.js";\n\n' +
        `export const CATALOGUE_SCHEMA = ${JSON.stringify(doc.schema)};\n\n` +
        "/** Every FW- id of the catalogue. */\n" +
        `export type CatalogueId = ${union(entries.map((m) => m.id))};\n\n` +
        "/** The ids TypeScript may emit: entries whose `sdk` list names typescript. */\n" +
        `export type TypeScriptCatalogueId = ${union(ts)};\n\n` +
        `export const TYPESCRIPT_IDS: readonly TypeScriptCatalogueId[] = ${literal(ts)};\n\n` +
        `export const CATALOGUE: readonly CatalogueEntry[] = ${literal(entries)};\n`
    );
}

const CHECK_KEYS = new Set([
    "type",
    "values",
    "source",
    "value",
    "span",
    "min",
    "max",
    "pattern",
    "int64_groups",
    "capture_labels",
    "items",
    "max_items",
    "min_items",
    "unique",
    "identity_mode",
]);

/**
 * A registry check in JavaScript regex syntax, with only the keys a check reads. Documentation
 * fields such as `examples` stay in the registry: sample secrets-shaped values in shipped source
 * trip secret scanners and no check reads them.
 */
function jsCheck(check) {
    const out = {};
    for (const [key, value] of Object.entries(check)) {
        if (!CHECK_KEYS.has(key)) {
            continue;
        }
        if (key === "pattern") {
            out[key] = value.replaceAll("(?P<", "(?<");
        } else if (key === "capture_labels") {
            out[key] = {
                ...value,
                pseudonymous_pattern: value.pseudonymous_pattern.replaceAll(
                    "(?P<",
                    "(?<",
                ),
            };
        } else if (key === "items") {
            out[key] = jsCheck(value);
        } else {
            out[key] = value;
        }
    }
    return out;
}

const ROW_KEYS = [
    "placement",
    "capture_points",
    "capture_point_kinds",
    "manifest_property",
];

function telemetryKeys() {
    const keysSource = "contracts/coverage/v1/registry/telemetry-keys-v1.json";
    const pointsSource =
        "contracts/coverage/v1/registry/capture-points-v1.json";
    const reg = readJson(keysSource);
    const points = readJson(pointsSource);
    const rows = {};
    for (const row of reg.keys) {
        const out = {};
        if (row.check) out.check = jsCheck(row.check);
        if (row.capture_check) out.capture_check = jsCheck(row.capture_check);
        for (const key of ROW_KEYS) {
            if (key in row) out[key] = row[key];
        }
        rows[row.key] = out;
    }
    const kinds = {};
    for (const point of points.capture_points) {
        kinds[point.id] = point.kind.split("/");
    }
    return (
        HEADER +
        `// Sources: ${keysSource} and ${pointsSource}.\n` +
        "// Each key's checks (patterns in JavaScript syntax), placements, records conditions and\n" +
        "// manifest property, and each capture point's kinds: what rule A (spec 050 §3.4), the\n" +
        "// Node's key checks and the manifest span form read. A test keeps it equal to the\n" +
        "// registries.\n\n" +
        'import type { TelemetryKeyRow } from "./types.js";\n\n' +
        `export const TELEMETRY_KEY_REVISION = ${reg.registry_revision};\n\n` +
        `export const TELEMETRY_KEYS: Readonly<Record<string, TelemetryKeyRow>> = ${literal(rows)};\n\n` +
        `export const CAPTURE_POINT_KINDS: Readonly<Record<string, readonly string[]>> = ${literal(kinds)};\n`
    );
}

const OUTPUTS = {
    "endpoint-table.generated.ts": endpointTable,
    "catalogue.generated.ts": catalogue,
    "telemetry-keys.generated.ts": telemetryKeys,
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [name, render] of Object.entries(OUTPUTS)) {
    const path = join(OUT, name);
    const text = render();
    let current = null;
    try {
        current = readFileSync(path, "utf8");
    } catch {
        current = null;
    }
    if (current === text) {
        continue;
    }
    if (check) {
        stale += 1;
        console.error(
            `${relative(ROOT, path)} differs from its contract: run node ${SCRIPT} and commit the result`,
        );
    } else {
        writeFileSync(path, text);
        console.log(`wrote ${relative(ROOT, path)}`);
    }
}
process.exit(stale === 0 ? 0 : 1);
