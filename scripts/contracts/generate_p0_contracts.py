class Writer:
    """Collects derived files; writes them, or reports which differ (``--check``)."""

    def __init__(self, root: Path, *, check: bool) -> None:
        self.root, self.check = root, check
        self.pending: dict[Path, bytes] = {}

    def read_text(self, rel: Path | str) -> str:
        rel = Path(rel)
        if rel in self.pending:
            return self.pending[rel].decode("utf-8")
        return (self.root / rel).read_text(encoding="utf-8")

    def read_json(self, rel: Path | str) -> Any:
        return json.loads(self.read_text(rel))

    def text(self, rel: Path | str, content: str) -> None:
        self.pending[Path(rel)] = content.encode("utf-8")

    def json(self, rel: Path | str, document: Any) -> None:
        self.text(rel, json.dumps(document, indent=2, ensure_ascii=False) + "\n")

    def finish(self) -> list[str]:
        drift = []
        for rel, content in sorted(self.pending.items()):
            path = self.root / rel
            if not path.is_file() or path.read_bytes() != content:
                drift.append(rel.as_posix())
                if not self.check:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(content)
        return drift


def registries(w: Writer) -> dict[str, Any]:
    return {
        name: w.read_json(COVERAGE / rel) for name, rel in coverage.REGISTRY.items()
    }


def sha_text(text: str) -> str:
    return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()


def canonical_digest(document: Any) -> str:
    return coverage.manifest_digest(document)


