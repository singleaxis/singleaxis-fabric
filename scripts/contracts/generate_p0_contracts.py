"""Regenerate the spec 049 P0 contract artifacts that are derived, not authored.

Spec 049 (rev 6.3) is the source of truth; ``validate_coverage_contracts.py``
checks every artifact this script writes. Derived here:

- the machine-readable ``check`` of each telemetry-key row (the validator text
  is the spec's; the check is its closed form) and the fixed confidence of each
  inference method;
- the coverage/v1 valid/invalid fixtures and vectors, the capture/v1 run-marker,
  records-input and manifest-record fixtures and the content/v2 split vectors;
- the pins of the three family manifests;
- the generated validator table in fabricguard's ``coverage_keys.go``;
- the fabriccontent exporter's role table and status-reason set
  (``roles_generated.go``, spec 049 §4.3);
- the capture/v1 manifest-record schema and the spec's generated blocks (via
  the validator's renderers).

``--check`` writes nothing and fails when any derived artifact would change;
``scripts/tests/test_contract_generators.py`` runs it. Without ``--check`` the
artifacts are rewritten in place.
"""

