def go_admitted(row: dict[str, Any]) -> bool:
    """Keys coverage_keys.go admits through its generated table."""
    check = row.get("check")
    return (
        check is not None
        and row.get("owner") != "receiver"
        and "admission" not in check
        and "span" not in check
    )


def render_go_table(reg: dict[str, Any]) -> str:
    patterns: dict[str, str] = {}

    def pattern(key: str, regex: str) -> str:
        match = re.fullmatch(r"\^([a-z]+)-\[0-9a-f\]\{32\}\$", regex)
        if match:
            return f'pseudonymPattern("{match.group(1)}")'
        if regex in GO_NAMED:
            name = GO_NAMED[regex]
            if name not in {"captureObjectIDPattern"}:
                patterns.setdefault(regex, name)
            return name
        patterns.setdefault(regex, GO_BY_KEY[key])
        return patterns[regex]

    def go(key: str, check: dict[str, Any]) -> str:
        kind = check["type"]
        if kind == "enum":
            return (
                "oneOf(toSet("
                + ", ".join(json.dumps(v) for v in check["values"])
                + "))"
            )
        if kind == "const":
            value = check["value"]
            return (
                f"constBool({str(value).lower()})"
                if isinstance(value, bool)
                else f"constStr({json.dumps(value)})"
            )
        if kind == "bool":
            return "isBool"
        if kind == "int":
            return (
                f"intIn({check['min']}, {check['max']})"
                if "max" in check
                else f"intAtLeast({check['min']})"
            )
        if kind == "datetime":
            return "isRFC3339"
        if kind == "string":
            var = pattern(key, check["pattern"])
            groups = check.get("int64_groups")
            if groups:
                return (
                    f"matchesInt64({var}, "
                    + ", ".join(json.dumps(g) for g in groups)
                    + ")"
                )
            return f"matches({var})"
        if kind == "array":
            return (
                f"sliceOf({check.get('min_items', 0)}, {check['max_items']}, "
                f"{str(bool(check.get('unique'))).lower()}, {go(key, check['items'])})"
            )
        raise ValueError(kind)

    rows = [
        (r["key"], go(r["key"], r["check"]))
        for r in reg["keys"]["keys"]
        if go_admitted(r)
    ]
    labels = sorted(
        r["key"]
        for r in reg["keys"]["keys"]
        if go_admitted(r)
        and "group" not in r["check"].get("capture_labels", {"group": None})
    )
    manifest_keys = sorted(
        r["key"] for r in reg["keys"]["keys"] if "manifest_property" in r
    )
    width = max(len(json.dumps(k)) for k, _ in rows) + 1
    out = [
        GO_BEGIN,
        "\n",
        "// coverageKeyValidators: every key the registry admits now, with its check.\n",
        "var coverageKeyValidators = map[string]func(pcommon.Value) bool{\n",
    ]
    out += [f"\t{(json.dumps(k) + ':').ljust(width)} {expr},\n" for k, expr in rows]
    out += [
        "}\n",
        "\n",
        "// operatorLabelKeys are operator labels (spec 049 §4.2 LABEL exposure): under\n",
        "// capture_labels pseudonymous the whole value must be lbl- + 32 hex.\n",
        "var operatorLabelKeys = toSet(\n",
    ]
    out += [f"\t{json.dumps(k)},\n" for k in labels]
    out += [
        ")\n",
        "\n",
        "// clearIdentityKeys keep their pre-049 admission under identity_mode: clear\n",
        "// (spec 049 §2.9 rule 7); a pseudonymous Node admits only the check.\n",
        "var clearIdentityKeys = toSet(\n",
    ]
    out += [
        f"\t{json.dumps(r['key'])},\n"
        for r in sorted(reg["keys"]["keys"], key=lambda r: r["key"])
        if go_admitted(r) and "identity_mode" in r["check"]
    ]
    out += [
        ")\n",
        "\n",
        "// manifestSpanKeys are the closed attributes of the fabric.capture_manifest span.\n",
        "var manifestSpanKeys = toSet(\n",
    ]
    out += [f"\t{json.dumps(k)},\n" for k in manifest_keys]
    out += [")\n", "\n", "var (\n"]
    width = max(len(name) for name in patterns.values())
    out += [
        f"\t{name.ljust(width)} = regexp.MustCompile(`{regex}`)\n"
        for regex, name in patterns.items()
    ]
    out += [")\n", "\n", GO_END]
    return "".join(out)


def generate_go(w: Writer) -> None:
    text = w.read_text(GO_TABLE)
    start, end = text.index(GO_BEGIN), text.index(GO_END) + len(GO_END)
    w.text(GO_TABLE, text[:start] + render_go_table(registries(w)) + text[end:])


CAP_BYTES = {"64 KiB": 65536, "256 KiB": 262144, "1 MiB": 1048576, "4 MiB": 4194304}


def render_go_roles(reg: dict[str, Any]) -> str:
    """The fabriccontent role table (spec 049 §4.3: the single role source)."""
    table = reg["roles"]

    def strs(values: list[str]) -> str:
        return "[]string{" + ", ".join(json.dumps(v) for v in values) + "}"

    out = [
        "// Copyright 2026 AI5Labs Research OPC Private Limited\n",
        "// SPDX-License-Identifier: Apache-2.0\n",
        "\n",
        "// Code generated by scripts/contracts/generate_p0_contracts.py from\n",
        "// contracts/coverage/v1/registry/content-roles-v1.json and vocabularies-v1.json.\n",
        "// DO NOT EDIT.\n",
        "\n",
        "package fabriccontentexporter\n",
        "\n",
        "// roleTableVersion is the role table this exporter enforces.\n",
        f'const roleTableVersion = "{table["schema_version"]}@{table["registry_revision"]}"\n',
        "\n",
        "// roleTable is every content role with its permitted boundaries, provenance,\n",
        "// media types and cap (capBytes 0: the configured max_body_bytes).\n",
        "var roleTable = map[string]roleRule{\n",
    ]
    width = max(len(json.dumps(row["role"])) + 1 for row in table["roles"])
    for row in table["roles"]:
        cap = 0 if row["cap"] == "max_body_bytes" else CAP_BYTES[row["cap"]]
        out.append(
            f"\t{(json.dumps(row['role']) + ':').ljust(width)} {{boundary: {strs(row['boundary'])}, "
            f"provenance: {strs(row['provenance'])}, media: {strs(row['media_types'])}, "
            f"capBytes: {cap}}},\n"
        )
    out += [
        "}\n",
        "\n",
        "// statusReasons is the closed coverage reason vocabulary a descriptor-only\n",
        "// not_captured record names in status_reason.\n",
        "var statusReasons = map[string]bool{\n",
    ]
    width = max(len(json.dumps(r["value"])) + 1 for r in reg["vocab"]["reason"])
    out += [
        f"\t{(json.dumps(r['value']) + ':').ljust(width)} true,\n"
        for r in reg["vocab"]["reason"]
    ]
    out += ["}\n"]
    return "".join(out)


def generate_go_roles(w: Writer) -> None:
    w.text(GO_ROLES, render_go_roles(registries(w)))


# ===================================================================== derived schema and spec blocks
def generate_rendered(w: Writer) -> None:
    reg = registries(w)
    manifest_schema = w.read_json(COVERAGE / coverage.SCHEMAS["manifest"])
    w.json(
        coverage.MANIFEST_RECORD_SCHEMA,
        coverage.render_manifest_record_schema(reg, manifest_schema),
    )
    text = w.read_text(coverage.SPEC)
    blocks = coverage.render_blocks(reg)

    def sub(match: re.Match[str]) -> str:
        name = match["name"]
        return f"<!-- generated:{name}:begin -->\n{blocks.get(name, match['body'])}<!-- generated:{name}:end -->"

    w.text(coverage.SPEC, coverage.BLOCK_RE.sub(sub, text))


def generate(root: Path, *, check: bool) -> list[str]:
    w = Writer(root, check=check)
    generate_registry(w)
    generate_rendered(w)
    generate_coverage(w)
    generate_capture(w)
    generate_content(w)
    generate_pins(w)
    generate_go(w)
    generate_go_roles(w)
    return w.finish()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--repo-root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    parser.add_argument(
        "--check", action="store_true", help="fail if regeneration would change a file"
    )
    args = parser.parse_args(argv)
    drift = generate(args.repo_root, check=args.check)
    if args.check and drift:
        print(
            "derived contract artifacts are stale:\n  " + "\n  ".join(drift),
            file=sys.stderr,
        )
        return 1
    print(
        ("stale: " if args.check else "rewrote: ")
        + (", ".join(drift) if drift else "nothing")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
