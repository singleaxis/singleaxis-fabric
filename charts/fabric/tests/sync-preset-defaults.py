"""Write (or with --check, compare) charts/fabric/presets/defaults.yaml.

`preset` (spec 058 section 10.1) applies a profile file's value only where the
effective value still equals the chart default, so the chart needs the default
of every value a profile file names. This script copies those defaults from
values.yaml and charts/otel-collector/values.yaml; tests/test-presets.sh runs
it with --check, so a changed default or profile cannot leave the file stale.

Needs PyYAML.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

CHART = Path(__file__).resolve().parent.parent
PROFILES = ("shadow-dev.yaml", "shadow-production.yaml", "shadow-production-host-ingress.yaml")
TARGET = CHART / "presets" / "defaults.yaml"
HEADER = (
    "# Generated by tests/sync-preset-defaults.py from values.yaml and\n"
    "# charts/otel-collector/values.yaml. Do not edit: the chart default of every\n"
    "# value a profile file names, which `preset` compares against (spec 058 10.1).\n"
)


def load(path: Path) -> dict[str, Any]:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def pick(profile: Any, defaults: Any) -> Any:
    """The part of ``defaults`` that ``profile`` names (leaf by leaf)."""
    if not isinstance(profile, dict):
        return defaults
    out = {}
    for key, value in profile.items():
        if isinstance(defaults, dict) and key in defaults:
            out[key] = pick(value, defaults[key])
    return out


def merge(into: dict[str, Any], more: dict[str, Any]) -> dict[str, Any]:
    for key, value in more.items():
        if isinstance(value, dict) and isinstance(into.get(key), dict):
            merge(into[key], value)
        else:
            into[key] = value
    return into


def render() -> str:
    defaults = load(CHART / "values.yaml")
    defaults["otel-collector"] = merge(
        load(CHART / "charts" / "otel-collector" / "values.yaml"),
        defaults.get("otel-collector") or {},
    )
    picked: dict[str, Any] = {}
    for name in PROFILES:
        merge(picked, pick(load(CHART / "profiles" / name), defaults))
    return HEADER + yaml.safe_dump(picked, sort_keys=True, default_flow_style=False)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text:
            print(
                f"FAIL: {TARGET.relative_to(CHART.parent.parent)} is stale. "
                "Fix: python3 charts/fabric/tests/sync-preset-defaults.py",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
