#!/usr/bin/env bash
# Spec 058 §16.3 E2 acceptance on a real cluster (kind), after ttfr-kubernetes:
#
#  0. G4 still holds: `fabric verify --kubernetes` exits 0 with `corroboration: complete`
#     for the fixture agent's run (the TTFR page installed the production-host-sensor
#     preset with one `fabric up --kubernetes`, one label and one annotation).
#  The audit's three workarounds, as regression tests that pass with no manual step:
#  1. the host sensor behind the chart's default-deny NetworkPolicy (F5): the policy is
#     in force (a probe from another namespace cannot reach the sensor's ingress port),
#     and the sensor still delivers;
#  2. kind's `kubelet.slice` cgroup layout (F4): the sensor scopes the agent pods with
#     no cgroup override;
#  3. an S3-compatible content store behind a private CA (F6): one chart value
#     (`content.s3.caSecret`) in the customer's destination.yaml, content objects land
#     in the store, and verify checked the agent's decisions against them (step 0).
#  4. A pod whose RuntimeClass handler is gVisor (`runsc`) is reported
#     `unsupported_runtime` by the sensor and by `fabric doctor --kubernetes`.
#  5. Webhook outage: with the injector scaled to zero an annotated pod is admitted
#     within the 2 s timeout and runs uncaptured; `fabric doctor --kubernetes` says why.
#  6. `fabric down --kubernetes` keeps the generated Secrets; `--purge` removes them.
#
# Environment: WORK (the ttfr_kubernetes.py --work directory, run with --keep-cluster:
# its kubeconfig, chart and project), AGENT_IMAGE, KIND_CLUSTER (to inspect the node),
# FABRIC (default: the CLI the TTFR page installed, WORK/venv/bin/fabric).
# Needs kubectl, helm, docker, jq and python3 with the `cryptography` package.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "${here}/../../../.." && pwd)"
: "${WORK:?set WORK to the ttfr_kubernetes.py work directory}"
: "${AGENT_IMAGE:?}" "${KIND_CLUSTER:?}"
export KUBECONFIG="${WORK}/kubeconfig"
export FABRIC_CHART="${WORK}/chart"
FABRIC="${FABRIC:-${WORK}/venv/bin/fabric}"
PYTHON="${PYTHON:-python3}"
fixtures="${repo}/scripts/ttfr/kubernetes/fixtures.py"
project="${WORK}/project"
release=fabric
ns=fabric-system
agents=agents
tenant=acme
tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT

log() { printf '== %s\n' "$*"; }
fail() {
  printf 'FAIL: %s\n' "$*" >&2
  kubectl get pods -A -o wide >&2 || true
  kubectl -n "${ns}" logs -l app.kubernetes.io/name=fabric-host-emitter --tail=20 >&2 || true
  exit 1
}
# The workstation's AWS configuration for the customer's content store (read-only keys,
# its CA and address), as the TTFR page ran with it.
while IFS='=' read -r name value; do export "${name}=${value}"; done \
  < <(jq -r '.aws_environment | to_entries[] | "\(.key)=\(.value)"' "${project}/fixture.json")
fabric() { (cd "${project}" && "${FABRIC}" "$@"); }
# The newest health line of the sensor on the (single) kind node.
health() {
  kubectl -n "${ns}" logs -l app.kubernetes.io/name=fabric-host-emitter --tail=400 \
    | grep ' health ' | tail -n 1
}
counter() { sed -n "s/.* $1=\([0-9]*\).*/\1/p" <<<"$2"; }
wait_health() {  # FIELD MIN SECONDS: the sensor reports FIELD >= MIN
  local deadline=$((SECONDS + $3)) line value
  while :; do
    line="$(health)"
    value="$(counter "$1" "${line}")"
    [[ -n "${value}" ]] && (( value >= $2 )) && { printf '%s' "${line}"; return 0; }
    (( SECONDS < deadline )) || { printf '%s' "${line}"; return 1; }
    sleep 5
  done
}
injector="$(kubectl -n "${ns}" get deployment -l "app.kubernetes.io/component=injector,app.kubernetes.io/instance=${release}" -o name)"
[[ -n "${injector}" ]] || fail "no injector Deployment in ${ns}"

# --- 0. G4: verify exits 0 and the host sensor corroborates the run -------------------
log "fabric verify --kubernetes (G4)"
fabric verify --kubernetes --spans destination-export >"${tmp}/verify.out" 2>&1 \
  || { cat "${tmp}/verify.out" >&2; fail "fabric verify --kubernetes did not exit 0"; }
grep -q 'corroboration: complete' "${tmp}/verify.out" || { cat "${tmp}/verify.out" >&2; fail "the run is not corroborated"; }
grep -q 'FC-069' "${tmp}/verify.out" || fail "verify did not judge a complete run"
for secret in "${ns}/fabric-ca" "${ns}/fabric-node-receiver-tls" "${agents}/fabric-agent"; do
  managed="$(kubectl -n "${secret%%/*}" get secret "${secret#*/}" -o jsonpath='{.metadata.labels.app\.kubernetes\.io/managed-by}')"
  [[ "${managed}" == fabric-cli ]] || fail "Secret ${secret} was not generated by Fabric (${managed:-missing})"
done

# --- 1. workaround F5: the sensor behind the default-deny policy ----------------------
log "host sensor behind the default-deny NetworkPolicy"
kubectl -n "${ns}" get networkpolicy -o json \
  | jq -e '[.items[] | select(.spec.podSelector == {} and ((.spec.policyTypes // []) | index("Egress"))
                         and ((.spec.egress // []) | length == 0))] | length >= 1' >/dev/null \
  || fail "the release has no default-deny NetworkPolicy (the production preset sets networkPolicy.denyDefault)"
kubectl -n "${ns}" get networkpolicy -o json \
  | jq -e '[.items[] | select(.spec.podSelector.matchLabels["app.kubernetes.io/name"] == "fabric-host-emitter")] | length >= 1' \
    >/dev/null || fail "no chart NetworkPolicy lets the host sensor out (networkPolicy.hostSensorEgress)"
node_service="$(kubectl -n "${ns}" get service -l app.kubernetes.io/name=otel-collector -o jsonpath='{.items[0].metadata.name}')"
sensor_port="$(kubectl -n "${ns}" get service "${node_service}" -o json \
  | jq -r '[.spec.ports[] | select(.name | test("grpc")) | .port] | map(select(. != 4317)) | max')"
# Negative control: the policy must really be enforced, or this test proves nothing.
kubectl create namespace f058-np-probe --dry-run=client -o yaml | kubectl apply -f - >/dev/null
kubectl -n f058-np-probe run np-probe --image="${AGENT_IMAGE}" --image-pull-policy=IfNotPresent \
  --restart=Never --command -- python -c "import socket, sys
try:
    socket.create_connection(('${node_service}.${ns}.svc', ${sensor_port}), 4).close()
except OSError as exc:
    print('blocked', type(exc).__name__); sys.exit(0)
print('reached'); sys.exit(3)" >/dev/null
kubectl -n f058-np-probe wait --for=jsonpath='{.status.phase}'=Succeeded pod/np-probe --timeout=120s >/dev/null \
  || { kubectl -n f058-np-probe logs np-probe >&2 || true
       fail "a pod outside the sensor's selector reached the Node's sensor port ${sensor_port}: this cluster does not enforce NetworkPolicy, so the default-deny regression cannot be tested here (use a CNI that enforces it)"; }
kubectl delete namespace f058-np-probe --wait=false >/dev/null
line="$(wait_health pods_scoped 1 90)" || fail "the sensor scopes no agent pod: ${line}"
recent="$(kubectl -n "${ns}" logs -l app.kubernetes.io/name=fabric-host-emitter --since=60s)"
grep -q 'export retry pending' <<<"${recent}" && { tail -5 <<<"${recent}" >&2; fail "the sensor cannot deliver to the Node behind the policy"; }
grep -q 'FC-135' "${tmp}/verify.out" && fail "verify reported a sensor export failure"

# --- 2. workaround F4: kind's kubelet.slice layout -------------------------------------
log "kind's kubelet.slice cgroup layout"
node="$(kind get nodes --name "${KIND_CLUSTER}" | head -n 1)"
docker exec "${node}" test -d /sys/fs/cgroup/kubelet.slice/kubelet-kubepods.slice \
  || fail "the kind node does not use the kubelet.slice layout this test is about"
kubectl -n "${ns}" get daemonset -l "app.kubernetes.io/component=host-sensor,app.kubernetes.io/instance=${release}" -o json \
  | jq -e '(.items | length == 1)
           and ([.items[].spec.template.spec.containers[].env[]? | select(.name == "EMIT_AGENT_CGROUP_ROOTS")] | length == 0)' \
    >/dev/null || fail "the sensor was given a cgroup override (the workaround this replaces)"
[[ "$(counter pods_unscoped_cgroup_not_found "${line}")" == 0 ]] || fail "selected pods without a cgroup: ${line}"
printf '   %s\n' "$(grep -o 'pods_selected=[0-9]* pods_scoped=[0-9]*' <<<"${line}")"

# --- 3. workaround F6: a private-CA S3-compatible content store -------------------------
log "content to an S3-compatible store behind a private CA"
kubectl -n "${ns}" get statefulset -l app.kubernetes.io/name=otel-collector -o json \
  | jq -e '.items[0].spec.template.spec as $pod
           | ([$pod.containers[0].env[] | select(.name == "AWS_CA_BUNDLE")] | length == 1)
             and ([$pod.volumes[] | select(.secret.secretName == "fabric-content-s3-ca"
                                           or any(.projected.sources[]?; .secret.name == "fabric-content-s3-ca"))]
                  | length == 1)' \
    >/dev/null || fail "the Node does not trust the store's CA through content.s3.caSecret"
objects="$("${PYTHON}" "${fixtures}" s3-objects --tenant "${tenant}" | tail -n 1)"
(( objects > 0 )) || { kubectl -n "${ns}" logs -l app.kubernetes.io/name=otel-collector --tail=40 >&2 || true
                       fail "no content object reached the private-CA store"; }
printf '   %s content object(s) in the store\n' "${objects}"
grep -q 'content store: s3://' "${tmp}/verify.out" || fail "verify did not read the agent's model bodies from the store"
kubectl -n "${ns}" logs -l app.kubernetes.io/name=otel-collector --tail=400 \
  | grep -Eqi 'x509|certificate signed by unknown authority' && fail "the Node logged a certificate error for the store"

# --- 4. a gVisor RuntimeClass pod is unsupported_runtime, never silent ----------------
log "gVisor RuntimeClass pod"
kubectl apply -f - >/dev/null <<'EOF'
{"apiVersion": "node.k8s.io/v1", "kind": "RuntimeClass", "metadata": {"name": "f058-gvisor"}, "handler": "runsc"}
EOF
# kind has no runsc: the pod is scheduled and never starts, which is all the sensor needs
# to see (its RuntimeClass handler); a real gVisor node would run it.
kubectl -n "${agents}" apply -f - >/dev/null <<EOF
{"apiVersion": "v1", "kind": "Pod",
 "metadata": {"name": "agent-gvisor", "annotations": {"fabric.singleaxis.ai/inject": "python"}},
 "spec": {"runtimeClassName": "f058-gvisor", "restartPolicy": "Never",
          "containers": [{"name": "agent", "image": "${AGENT_IMAGE}", "imagePullPolicy": "IfNotPresent"}]}}
EOF
line="$(wait_health pods_unscoped_unsupported_runtime 1 120)" \
  || fail "the sensor did not report the gVisor pod unsupported_runtime: ${line}"
kubectl -n "${ns}" logs -l app.kubernetes.io/name=fabric-host-emitter --tail=400 \
  | grep -q 'WARN pod scope: .*unsupported_runtime' || fail "no WARN line names unsupported_runtime"
set +e
fabric doctor --kubernetes >"${tmp}/doctor-gvisor.out" 2>&1
set -e
grep -q 'unsupported_runtime' "${tmp}/doctor-gvisor.out" && grep -q 'FC-138' "${tmp}/doctor-gvisor.out" \
  || { cat "${tmp}/doctor-gvisor.out" >&2; fail "doctor --kubernetes does not report the gVisor pod"; }
fabric plan --kubernetes >"${tmp}/plan.out" 2>&1 || true
grep -q 'FC-138' "${tmp}/plan.out" || { cat "${tmp}/plan.out" >&2; fail "plan --kubernetes does not name the gVisor RuntimeClass"; }
kubectl -n "${agents}" delete pod agent-gvisor --wait=false >/dev/null
kubectl delete runtimeclass f058-gvisor >/dev/null

# --- 5. webhook outage -------------------------------------------------------------------
log "webhook outage"
replicas="$(kubectl -n "${ns}" get "${injector}" -o jsonpath='{.spec.replicas}')"
kubectl -n "${ns}" scale "${injector}" --replicas=0 >/dev/null
kubectl -n "${ns}" wait --for=delete pod -l app.kubernetes.io/name=fabric-injector --timeout=120s >/dev/null || true
now_ms() { "${PYTHON}" -c 'import time; print(int(time.time() * 1000))'; }
start="$(now_ms)"
kubectl -n "${agents}" run agent-outage --image="${AGENT_IMAGE}" --image-pull-policy=IfNotPresent \
  --restart=Never --annotations=fabric.singleaxis.ai/inject=python >/dev/null
elapsed_ms=$(( $(now_ms) - start ))
(( elapsed_ms < 5000 )) || fail "admission took ${elapsed_ms} ms with the injector down (the webhook timeout is 2 s)"
kubectl -n "${agents}" wait --for=jsonpath='{.status.phase}'=Succeeded pod/agent-outage --timeout=180s >/dev/null \
  || fail "the annotated pod did not run with the injector down"
kubectl -n "${agents}" get pod agent-outage -o json \
  | jq -e '.metadata.annotations["fabric.singleaxis.ai/injected"] == null and ((.spec.containers[0].env // []) | length == 0)' \
    >/dev/null || fail "a pod admitted during the outage was changed"
set +e
fabric doctor --kubernetes >"${tmp}/doctor-outage.out" 2>&1
code=$?
set -e
(( code == 1 )) || { cat "${tmp}/doctor-outage.out" >&2; fail "doctor --kubernetes exited ${code} during the outage (want 1)"; }
grep -q 'FC-129' "${tmp}/doctor-outage.out" && grep -q 'agent-outage' "${tmp}/doctor-outage.out" \
  || { cat "${tmp}/doctor-outage.out" >&2; fail "doctor --kubernetes does not say why the pod runs uncaptured"; }
printf '   admission with the injector down: %d ms\n' "${elapsed_ms}"
kubectl -n "${ns}" scale "${injector}" --replicas="${replicas}" >/dev/null
kubectl -n "${ns}" rollout status "${injector}" --timeout=180s >/dev/null
kubectl -n "${agents}" delete pod agent-outage --wait=false >/dev/null

# --- 6. down keeps the Secrets; --purge removes them ------------------------------------
log "fabric down --kubernetes"
fabric down --kubernetes >"${tmp}/down.out" 2>&1 || { cat "${tmp}/down.out" >&2; fail "fabric down --kubernetes failed"; }
grep -q 'FC-149' "${tmp}/down.out" || fail "down did not say the Secrets are kept"
kubectl -n "${ns}" get secret fabric-ca >/dev/null || fail "down deleted the generated CA"
kubectl -n "${agents}" get secret fabric-agent >/dev/null || fail "down deleted the agent Secret"
kubectl -n "${agents}" get deployment support-agent >/dev/null || fail "down touched the customer's workload"
fabric down --kubernetes --purge >"${tmp}/purge.out" 2>&1 || { cat "${tmp}/purge.out" >&2; fail "down --purge failed"; }
[[ -z "$(kubectl -n "${ns}" get secret -l app.kubernetes.io/managed-by=fabric-cli -o name)" ]] \
  || fail "--purge left generated Secrets in ${ns}"
kubectl -n "${ns}" get secret fabric-node-export-auth >/dev/null || fail "--purge deleted the customer's own Secret"

printf 'PASS: E2 acceptance (G4, three audit workarounds, gVisor, webhook outage) on kind\n'
